"""Generate the effect table of docs/protocol.md section 6 from the code.

Sources of truth: the variant order in include/fnvcoop/effect.h (= the wire tag) and the ioE() serializers in src/wire.cpp (= the
field list and encodings). Semantic remarks that the code cannot say live in NOTES below, next to the effect they describe.

Usage:
  python -I synccore/tools/gen_effect_table.py --write    rewrite the table between the markers in docs/protocol.md
  python -I synccore/tools/gen_effect_table.py --check    exit 1 if the document drifted from the code (the ctest `drift_effect_table`)
  python -I synccore/tools/gen_effect_table.py --check --mutate
                                                          self-test: corrupts the generated table first; must exit 1 (twin)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EFFECT_H = ROOT / "include" / "fnvcoop" / "effect.h"
WIRE_CPP = ROOT / "src" / "wire.cpp"
PROTOCOL_MD = ROOT.parent / "docs" / "protocol.md"
BEGIN = "<!-- BEGIN EFFECT TABLE (generated by synccore/tools/gen_effect_table.py from effect.h + wire.cpp; do not edit by hand) -->"
END = "<!-- END EFFECT TABLE -->"

NOTES = {
    "SetStage": "merge = max",
    "SetObjective": "flags: bit0 displayed, bit1 completed. A host-origin write is the exact flag state (a hide survives resync and late join); a guest-origin write only adds bits",
    "ModActorValue": "av 0x10000 = experience",
    "SetScriptVar": "index <= 0xFFFF",
    "CompanionOwner": "owner < 8; active false = dismiss; kind 0 humanoid, 1 critter",
    "ForcedDialogue": "event, not state; initiator < 8",
    "BarrierArrive": "required = slot mask",
    "SetFactionRank": "rank < 0 = removed",
    "SetPerk": "rank 0 = removed",
    "FailQuest": "sticky; implies completed (shadow state sets both questFailed and questCompleted)",
    "SpawnRef": "id is 0xFF-prefixed and host allocated (PlaceAtMe / PlaceLeveledActorAtMe)",
    "DespawnRef": "id is 0xFF-prefixed; tombstone, a later SpawnRef of the same id is ignored",
    "ObjectState": "mask <= 15: bit0 open, bit1 lock, bit2 destroyed, bit3 activate-once",
    "RefScriptVar": "index <= 0xFFFF; object / NPC script variable",
    "RefAddItem": "inventory of a non-player ref",
    "AddTopic": "journal, shared",
    "AddNote": "shared",
    "SetMapMarker": "flags bit0 visible, bit1 fast travel allowed; <= 3",
    "ForceActiveQuest": "per player UI focus; Default = the initiator",
    "RequestSave": "kind 0 autosave, 1 systemsave, 2 forcesave; EVENT",
    "SetWeather": "force = ForceWeather",
    "SetTimeScale": "SetGlobalTimeMultiplier, 0 = never set",
    "AdvanceTime": "sleep / wait; EVENT",
}


def variant_order(text):
    m = re.search(r"using Effect = std::variant<(.*?)>;", text, re.S)
    if not m:
        raise SystemExit("effect.h: `using Effect = std::variant<...>` not found")
    return [t.strip() for t in m.group(1).split(",") if t.strip()]


def balanced_body(text, start):
    """Text of the {...} block whose opening brace is at text[start]."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1:i]
    raise SystemExit("wire.cpp: unbalanced braces")


def serializers(text):
    out = {}
    for m in re.finditer(r"void ioE\(Archive&(?: a)?, (\w+)&(?: e)?\)\s*\{", text):
        out[m.group(1)] = balanced_body(text, m.end() - 1)
    return out


def fields_of(body):
    alias = {m.group(1): m.group(2) for m in re.finditer(r"uint32_t (\w+) = e\.(\w+);", body)}
    found = []
    for m in re.finditer(r"io\(a, e\.(\w+)\)|a\.(u8|u16|u32|u64|varu32|varu|vari32|vari|f32|f64|boolean|str)\((?:e\.)?(\w+)\)", body):
        if m.group(1):
            name = m.group(1)
            found.append(("to" if name == "to" else name, m.start()))
        else:
            name = alias.get(m.group(3), m.group(3))
            found.append((f"{m.group(2)} {name}", m.start()))
    return [f for f, _ in sorted(found, key=lambda x: x[1])]


def table():
    order = variant_order(EFFECT_H.read_text(encoding="utf-8"))
    wire = WIRE_CPP.read_text(encoding="utf-8")
    ser = serializers(wire)
    names = re.search(r"static const char\* names\[\] = \{(.*?)\};", wire, re.S)
    listed = re.findall(r'"(\w+)"', names.group(1)) if names else []
    if listed != order:
        raise SystemExit(f"wire.cpp effectName() table differs from the variant order in effect.h:\n  names:   {listed}\n  variant: {order}")
    missing = [n for n in order if n not in ser]
    if missing:
        raise SystemExit(f"wire.cpp has no ioE() for: {missing}")
    stale = [n for n in NOTES if n not in order]
    if stale:
        raise SystemExit(f"NOTES names effects that no longer exist: {stale}")
    rows = ["| Tag | Effect | Fields |", "|---|---|---|"]
    for tag, name in enumerate(order):
        f = fields_of(ser[name])
        text = ", ".join(f) if f else "(none)"
        if name in NOTES:
            text += f" ({NOTES[name]})"
        rows.append(f"| {tag} | {name} | {text} |")
    return "\n".join(rows)


def main(argv):
    block = f"{BEGIN}\n{table()}\n{END}"
    if "--mutate" in argv:   # self-test (twin): the checker must notice a corrupted table
        block = block.replace("| 0 | SetStage |", "| 1 | SetStage |", 1)
    doc = PROTOCOL_MD.read_text(encoding="utf-8")
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    have = pat.search(doc)
    if "--write" in argv:
        if have:
            doc = pat.sub(lambda _: block, doc, count=1)
        else:
            m = re.search(r"\| Tag \| Effect \| Fields \|\n\|---\|---\|---\|\n(?:\|.*\|\n)+", doc)
            if not m:
                raise SystemExit("protocol.md: no effect table to replace")
            doc = doc[:m.start()] + block + "\n" + doc[m.end():]
        PROTOCOL_MD.write_text(doc, encoding="utf-8", newline="\n")
        print("docs/protocol.md effect table regenerated")
        return 0
    if not have:
        print("DRIFT: docs/protocol.md has no generated effect table (run --write)")
        return 1
    if have.group(0) != block:
        old, new = have.group(0).splitlines(), block.splitlines()
        for i, (a, b) in enumerate(zip(old, new)):
            if a != b:
                print(f"DRIFT at table line {i}:\n  doc:  {a}\n  code: {b}")
                break
        else:
            print(f"DRIFT: the document has {len(old)} lines, the code {len(new)}")
        print("run: python -I synccore/tools/gen_effect_table.py --write")
        return 1
    print(f"effect table in sync ({len(new := block.splitlines()) - 4} effects)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
