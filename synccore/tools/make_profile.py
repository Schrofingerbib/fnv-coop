#!/usr/bin/env python
"""Builds synccore/data/goodsprings_profile.txt from L3's static analysis (out/questdata/effects.json.gz).

The soak simulator (synccore/soak/soak.cpp) replays a realistic traffic shape for the Goodsprings milestone quests
(VCG01 Ain't That a Kick in the Head, VCG02 Back in the Saddle, VMS16 Ghost Town Gunfight): the effects of every stage script
(one txn each), the effects of the object/quest script blocks, and how many quest-variable writes the per-frame quest blocks do.

Line format (whitespace separated, '#' comments):
  Q <edid> <Plugin.esm:HEX>                         quest identity
  S <edid> <stage> <varWrites>                      a stage script (one txn); following E lines belong to it
  B <scriptEdid> <block> <owner> <varWrites>        an object/quest script block; following E lines belong to it
  E <Effect> <args...>                              SetStage q stage | SetObjective q obj flags | SetGlobal g value | EnableRef r | DisableRef r |
                                                    AddItem item count | RemoveItem item count | ModActorValue av delta | ModReputation f fame infamy |
                                                    StartQuest q | StopQuest q | CompleteQuest q | MoveRef r dest
  V <edid> <writesPerFrame>                         per-frame quest variable writes of that quest's GameMode/MenuMode blocks
"""
import gzip, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'out', 'questdata', 'effects.json.gz')
DST = os.path.join(ROOT, 'synccore', 'data', 'goodsprings_profile.txt')
WANT = ['VCG01', 'VCG02', 'VMS16']


def eff_line(e):
    t = e['type']
    if t == 'SetStage': return f"E SetStage {e['quest']} {e['stage']}"
    if t == 'SetObjective': return f"E SetObjective {e['quest']} {e['objective']} {e.get('flags', 1)}"
    if t == 'SetGlobal': return f"E SetGlobal {e['global']} {e['value']}"
    if t in ('EnableRef', 'DisableRef'): return f"E {t} {e['ref']}"
    if t in ('AddItem', 'RemoveItem'): return f"E {t} {e['item']} {e.get('count', 1)}"
    if t == 'ModActorValue': return f"E ModActorValue {1 if e.get('av_name') == 'XP' else 2} {e.get('delta', 0)}"
    if t == 'ModReputation':
        a = e.get('args') or ['0', '0']
        try: fame, infamy = int(float(a[0])), int(float(a[1]))
        except Exception: fame, infamy = 1, 0
        return f"E ModReputation {e['faction']} {fame} {infamy}"
    if t in ('StartQuest', 'StopQuest', 'CompleteQuest'): return f"E {t} {e['quest']}"
    if t == 'MoveRef': return f"E MoveRef {e['ref']} {e.get('dest', 'FalloutNV.esm:000000')}"
    return None   # AddPerk etc.: outside the effect vocabulary


def main():
    d = json.load(gzip.open(SRC, 'rt'))
    quests = {}
    out = ['# generated by synccore/tools/make_profile.py from out/questdata/effects.json.gz - do not edit']
    for s in d['scripts']:
        if s.get('quest_edid') in WANT:
            quests[s['quest_edid']] = s['quest']
    for edid in WANT:
        out.append(f"Q {edid} {quests[edid]}")
    scripts = [s for s in d['scripts'] if s.get('quest_edid') in WANT]
    scripts.sort(key=lambda s: (WANT.index(s['quest_edid']), s['stage'], s.get('entry', 0)))
    for s in scripts:
        vw = sum(1 for u in s['unmodeled'] if u['fn'] == 'SetQuestVar')
        out.append(f"S {s['quest_edid']} {s['stage']} {vw}")
        for e in s['effects']:
            l = eff_line(e)
            if l: out.append(l)
    blocks = [b for b in d['blocks'] if any(w in (b.get('edid') or '') for w in WANT)]
    perframe = {w: 0 for w in WANT}
    for b in blocks:
        vw = sum(1 for u in b['unmodeled'] if u['fn'] == 'SetQuestVar')
        if b['owner'] == 'quest' and b['block'].lower() in ('gamemode', 'menumode'):
            for w in WANT:
                if w in b['edid'] and 'Test' not in b['edid']: perframe[w] += vw + len(b['effects'])
            continue
        if not b['effects'] and not vw: continue
        out.append(f"B {b['edid']} {b['block']} {b['owner']} {vw}")
        for e in b['effects']:
            l = eff_line(e)
            if l: out.append(l)
    for w in WANT:
        out.append(f"V {w} {perframe[w]}")
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, 'w', encoding='utf-8') as f:
        f.write('\n'.join(out) + '\n')
    print(f"wrote {DST}: {len(scripts)} stage scripts, {len(blocks)} blocks, per-frame writes {perframe}")


if __name__ == '__main__':
    sys.exit(main())
