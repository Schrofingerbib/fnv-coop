"""Auto-test generation: turn a shrunk fixture into a ready-to-run regression test.

Emits, into the chosen directory (default tools/flight/regress):
  <name>.json    the shrunk fixture, with "expect": {"converges": true} (the test passes once the bug is fixed)
  <name>.cmake   an add_test() line so a ctest case runs fnvcoop_replay on the fixture
and the generic runner `python -I tools/flight/regress.py <dir> --replay-cmd "..."` runs every fixture in a dir.
"""
import json
import os
import re

CMAKE_TEMPLATE = """# generated by tools/flight/gentest.py from a shrunk flight trace; do not edit by hand
# Bug it guards against: {sig}
# Steps: {n}. The test passes when fnvcoop_replay converges (exit code 0) on this fixture.
add_test(NAME flight_{name}
         COMMAND $<TARGET_FILE:{target}> {flag}${{CMAKE_CURRENT_LIST_DIR}}/{name}.json)
"""


def safe_name(s):
    s = re.sub(r"[^a-z0-9_]+", "_", s.lower()).strip("_")
    return s[:48] or "case"


def generate(shrunk, name, out_dir):
    name = safe_name(name)
    sig = (shrunk.get("shrunk") or {}).get("signature") or "unknown"
    fx = dict(shrunk)
    fx["expect"] = {"converges": True, "bug_signature": sig}
    os.makedirs(out_dir, exist_ok=True)
    jp = os.path.join(out_dir, name + ".json")
    cp = os.path.join(out_dir, name + ".cmake")
    with open(jp, "w") as f:
        json.dump(fx, f, indent=1, sort_keys=True)
        f.write("\n")
    simfuzz = fx.get("format") == "simfuzz-1"
    with open(cp, "w") as f:
        f.write(CMAKE_TEMPLATE.format(sig=sig.replace("\n", " "), n=len(fx.get("ops" if simfuzz else "steps", [])), name=name,
                                      target="fnvcoop_simfuzz" if simfuzz else "fnvcoop_replay", flag="--replay " if simfuzz else ""))
    return [jp, cp]
