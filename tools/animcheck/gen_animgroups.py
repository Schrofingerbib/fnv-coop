"""Regenerate animgroups.py (animation group id -> name) from the xNVSE enum TESAnimGroup::kAnimGroup_*.

Usage: python -I tools/animcheck/gen_animgroups.py
The enum order is the engine's animGroup id (TESAnimGroup::animGroup, one byte). Source: third_party/NVSE/nvse/nvse/NiNodes.h.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "third_party" / "NVSE" / "nvse" / "nvse" / "NiNodes.h"
OUT = Path(__file__).resolve().parent / "animgroups_table.py"


def main() -> int:
    text = SRC.read_text(encoding="latin1")
    start = text.index("kAnimGroup_Idle")
    end = text.index("kAnimGroup_Max", start)
    names = re.findall(r"kAnimGroup_(\w+)", text[start:end])
    lines = ['"""GENERATED by gen_animgroups.py from xNVSE NiNodes.h. Do not edit."""', "", "NAMES = ("]
    for i in range(0, len(names), 8):
        lines.append("    " + ", ".join(repr(n) for n in names[i:i + 8]) + ",")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(names)} groups")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
