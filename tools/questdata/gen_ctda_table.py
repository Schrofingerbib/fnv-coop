"""Generate ctda_funcs.py from xEdit's wbDefinitionsFNV.pas (dev-4.1.6).
Usage: python gen_ctda_table.py path/to/wbDefinitionsFNV.pas"""
import re, sys
src = open(sys.argv[1], encoding='latin1').read()
rows = re.findall(r"\(Index:\s*(\d+);\s*Name:\s*'([^']+)'(?:;\s*ParamType1:\s*(\w+))?(?:;\s*ParamType2:\s*(\w+))?", src)
out = ['# Generated by gen_ctda_table.py from xEdit wbDefinitionsFNV.pas (dev-4.1.6). index -> (name, ptype1, ptype2)', 'FUNCS = {']
for i, n, p1, p2 in rows:
    out.append(f"    {int(i)}: ({n!r}, {p1 or None!r}, {p2 or None!r}),")
out.append('}')
open('ctda_funcs.py', 'w').write('\n'.join(out) + '\n')
print(len(rows), 'functions')
