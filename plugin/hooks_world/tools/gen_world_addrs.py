#!/usr/bin/env python3
"""Regenerate plugin/hooks_world/world_addrs.h from tests/world_code/prologues.txt (written by dump_prologues.py from a LIVE game).

    python -I plugin/hooks_world/tools/gen_world_addrs.py

Cmd_* entries become HookSpecs (detoured; retBytes 0 = cdecl `ret`, confirmed by disassembly of each handler's own epilogue).
Call_* entries become CallSpecs: engine functions we only CALL; their first 16 bytes are re-checked at run time before the first call.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "tests", "world_code", "prologues.txt")
OUT = os.path.join(HERE, "..", "world_addrs.h")

# Evidence per entry, kept next to the generated table (what was verified and how).
NOTES = {
    "Cmd_MarkForDelete": "opcode 0x11BB, needsParent, 0 params; ret at 0x5D8E74",
    "Cmd_SetEssential": "opcode 0x1003, params (ActorBase, int opt default 0 -> essential = value > 0); ret at 0x5CD8E3",
    "Cmd_SetActorRefEssential": "opcode 0x1273, params (int) on the reference; essential = value > 0; ret at 0x5DFDDE",
    "Cmd_SetRestrained": "opcode 0x10F3, params (int) on the reference (RTTI cast to Actor, then restrain); ret at 0x5D09B2",
    "Cmd_SetEnemy": "opcode 0x1078, params (Faction, Faction, int opt, int opt); ret at 0x5C82B1",
    "Cmd_SetAlly": "opcode 0x1079, params (Faction, Faction, int opt, int opt); ret at 0x5C81E1",
    "Cmd_RestoreActorValue": "opcode 0x1182, needsParent, params (ActorValue, float); ret at 0x5BE18E",
    "Cmd_IgnoreCrime": "opcode 0x10AB, needsParent, params (int): actor ignore-crime flag = value > 0; table entry 0x11923C8; ret in epilogue",
    "Cmd_SetPCEnemyOfFaction": "opcode 0x10C6, params (Faction, int): faction player-enemy flag = value != 0 (TESFaction fn 0x47EB90); table entry 0x1192800",
    "Cmd_ClearFactionPlayerEnemyFlag": "opcode 0x11C9, params (Faction): same TESFaction fn 0x47EB90 with 0; table entry 0x1195078; prologue spans 11 bytes to an instruction boundary",
    "Call_SkySingleton": "cdecl() -> object whose +0x10 is the current weather; used by the evaluator 0x59EBB0 of GetIsCurrentWeather",
    "Call_SkyCurrentWeather": "thiscall(obj) -> [obj+0x10] (TESWeather*, form type 0x35 checked by 0x59EBB0)",
    "Call_PlaceAtMe": "cdecl(ref, form, count, distance, direction, float health) -> TESObjectREFR* (first placed); called by Cmd_PlaceAtMe 0x5C4A70",
}


def parse(path):
    rows = []
    for line in open(path):
        m = re.match(r"(\S+)\s+0x([0-9a-f]+)\s+stolen=(\d+|None)\s+bytes16=([0-9a-f]{32})", line)
        if not m:
            continue
        rows.append((m.group(1), int(m.group(2), 16), int(m.group(3)) if m.group(3) != "None" else 0, bytes.fromhex(m.group(4))))
    return rows


def bytes_c(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}"


def main():
    rows = parse(SRC)
    if not rows:
        print("no rows in", SRC, file=sys.stderr)
        return 1
    hooks = [r for r in rows if r[0].startswith("Cmd_")]
    calls = [r for r in rows if r[0].startswith("Call_")]
    out = []
    out.append("// GENERATED by tools/gen_world_addrs.py from tests/world_code/prologues.txt -- do not edit.")
    out.append("// Source: nvbridge world.peek on a running FalloutNV.exe 1.4.0.525 (the live")
    out.append("// process image). Code dumps next to prologues.txt; evidence in internal lane notes.")
    out.append("#pragma once")
    out.append("#include <cstddef>")
    out.append("")
    out.append('#include "hook_patch.h"')
    out.append("")
    out.append("namespace world_addrs {")
    out.append("")
    for n, a, st, b in hooks:
        out.append("// %s" % NOTES.get(n, ""))
        out.append("inline constexpr nvhooks::HookSpec %s = {\"%s\", 0x%xu, %s, 16, %d, 0};" % (n, n, a, bytes_c(b), st))
    out.append("")
    out.append("inline const nvhooks::HookSpec* const kAll[] = {" + ", ".join("&" + r[0] for r in hooks) + "};")
    out.append("inline constexpr size_t kCount = sizeof(kAll) / sizeof(kAll[0]);")
    out.append("")
    out.append("// Engine functions we call (not detour). Re-verified against these bytes before the first use at run time.")
    out.append("struct CallSpec {")
    out.append("    const char* name;")
    out.append("    unsigned addr;")
    out.append("    unsigned char bytes[16];")
    out.append("};")
    for n, a, st, b in calls:
        out.append("// %s" % NOTES.get(n, ""))
        out.append("inline constexpr CallSpec %s = {\"%s\", 0x%xu, %s};" % (n, n, a, bytes_c(b)))
    out.append("inline const CallSpec* const kCalls[] = {" + ", ".join("&" + r[0] for r in calls) + "};")
    out.append("inline constexpr size_t kCallCount = sizeof(kCalls) / sizeof(kCalls[0]);")
    out.append("")
    out.append("}  // namespace world_addrs")
    open(OUT, "w", newline="\n").write("\n".join(out) + "\n")
    print("wrote", OUT, len(hooks), "hooks", len(calls), "calls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
