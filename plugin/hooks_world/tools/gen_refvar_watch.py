#!/usr/bin/env python3
"""Generate the ref-variable watch list: every reference that some script writes a variable of BY NAME (`set SomeRef.var to x`).

    python -I plugin/hooks_world/tools/gen_refvar_watch.py [--questdata out/questdata]

Those writes come from another script (a quest script, a stage result, a dialogue result, a trigger), so the ref itself may be in a cell
nobody has loaded, and its own script never runs to tell us. The host polls these refs wherever the player is (world_refvars.h).
Reads out/questdata (scripts.json.gz, infos.jsonl.gz, quests.json, refnames.json.gz); writes
    data/refvar_watch.json      [{"ref": "plugin:LOCALID", "edid": "...", "sig": "REFR", "vars": ["..."]}]  (sorted, reviewable)
    world_refvar_watch.h        the same as a constexpr table the plugin compiles in (no data file to ship)
Refs given by a local variable (`set myRef.var to x` where myRef is a `ref` variable) cannot be named here; the sweep covers them while loaded.
"""
import argparse
import gzip
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_JSON = os.path.join(HERE, "..", "data", "refvar_watch.json")
OUT_H = os.path.join(HERE, "..", "world_refvar_watch.h")
DEFAULT_QD = os.path.join(HERE, "..", "..", "..", "out", "questdata")
SET = re.compile(r"\bset\s+([A-Za-z_][A-Za-z0-9_]*)\.([A-Za-z_][A-Za-z0-9_]*)\s+to\b", re.I)
REF_SIGS = ("REFR", "ACHR", "ACRE")
# The follower framework (VNPCFollowers / the companion scripts) writes these on every companion; the companion lane (per-owner state, G32/G33)
# owns them. A ref is watched because of OTHER variables only.
FOLLOWER_VARS = {"combatstylemelee", "combatstyleranged", "followerswitchaggressive", "isfollowingdefault", "isfollowinglong", "waiting"}


def sources(node):
    """Every script source string under `node` (a dict with a 'source' key, or any nested structure)."""
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "source" and isinstance(v, str):
                yield v
            else:
                yield from sources(v)
    elif isinstance(node, list):
        for v in node:
            yield from sources(v)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--questdata", default=DEFAULT_QD)
    a = ap.parse_args()
    qd = a.questdata
    names = json.load(gzip.open(os.path.join(qd, "refnames.json.gz")))
    byedid = {}
    for k, v in names.items():
        if v.get("edid") and v.get("sig") in REF_SIGS:
            byedid[v["edid"].lower()] = (k, v["edid"], v["sig"])
    texts = []
    for s in json.load(gzip.open(os.path.join(qd, "scripts.json.gz"))):
        texts.extend(sources(s))
    with gzip.open(os.path.join(qd, "infos.jsonl.gz"), "rt", encoding="utf-8") as f:
        for line in f:
            texts.extend(sources(json.loads(line)))
    texts.extend(sources(json.load(open(os.path.join(qd, "quests.json"), encoding="utf-8"))))
    found = {}
    for t in texts:
        for m in SET.finditer(t):
            hit = byedid.get(m.group(1).lower())
            if hit and m.group(2).lower() not in FOLLOWER_VARS:
                found.setdefault(hit, set()).add(m.group(2))
    rows = []
    for (key, edid, sig), vars_ in found.items():
        plugin, local = key.split(":")
        rows.append({"ref": "%s:%s" % (plugin.lower(), local.upper().zfill(6)), "edid": edid, "sig": sig, "vars": sorted(vars_, key=str.lower)})
    rows.sort(key=lambda r: r["ref"])
    os.makedirs(os.path.dirname(OUT_JSON), exist_ok=True)
    with open(OUT_JSON, "w", newline="\n") as f:
        json.dump(rows, f, indent=1)
        f.write("\n")
    with open(OUT_H, "w", newline="\n") as f:
        f.write("// GENERATED by tools/gen_refvar_watch.py from out/questdata (data/refvar_watch.json is the same list) -- do not edit.\n")
        f.write("// Refs that a script writes a variable of by name (`set SomeRef.var to x`): polled wherever the player is.\n")
        f.write("#pragma once\n#include <cstddef>\n#include <cstdint>\n\nnamespace world_refvar_watch {\n\n")
        f.write("struct Entry {\n    const char* plugin;\n    uint32_t localId;\n};\n\n")
        f.write("inline constexpr Entry kRefs[] = {\n")
        for r in rows:
            plugin, local = r["ref"].split(":")
            f.write('    {"%s", 0x%s},  // %s\n' % (plugin, local, r["edid"]))
        f.write("};\ninline constexpr size_t kCount = sizeof(kRefs) / sizeof(kRefs[0]);\n\n}  // namespace world_refvar_watch\n")
    print("%d refs, %d variables" % (len(rows), sum(len(r["vars"]) for r in rows)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
