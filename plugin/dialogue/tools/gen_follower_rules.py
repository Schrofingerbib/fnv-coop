#!/usr/bin/env python3
"""Follower quest variable rules for the per-owner companion registry (gap G33), from the ESM extraction in out/questdata.

Writes plugin/dialogue/data/follower_rules.txt, read at runtime by fnvcoop_dlg::loadFollowerRules:
  quest <plugin>:<HEXID> <edid>
  flag <humanoid|critter|hasFollower|current> <var index>        (applies to the last quest line)
  companion <name> <humanoid|critter> hired=<i> fired=<i> available=<i> refs=<plugin>:<HEXID>[,...]

Quests: VNPCFollowers (the vanilla pair of party flags, the counters and a Hired/Fired/Available triple per companion), NVDLC01Followers
(Dead Money: Dean, Christine, Dog; its single-companion flag bHaveCompanion is the "has a follower" variable), NVDLC02FollowersQuest
(Honest Hearts: Follows-Chalk, Waking Cloud, Joshua Graham). Every variable index is looked up by NAME in the quest script, so a
mismatch with the script aborts the generator. `refs` are the placed references (ACHR / ACRE) of the companion's base forms: the
CompanionOwner effect names the reference, not the base.

Usage: python -I plugin/dialogue/tools/gen_follower_rules.py [--out file] [--check]
"""
import argparse, gzip, json, os, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
QD = os.path.join(ROOT, 'out', 'questdata')

# quest edid -> (script edid, {flag: var name}, [(companion, kind, [base edids], hired var, fired var, available var)])
QUESTS = [
    ('VNPCFollowers', 'VNPCFollowersQuestSCRIPT',
     {'humanoid': 'bHumanoidInParty', 'critter': 'bCritterInParty', 'hasFollower': 'bPlayerHasFollower', 'current': 'nCurrentFollowers'},
     [('Boone', 'humanoid', ['CraigBoone'], 'bBooneHired', 'bBooneFired', 'bBooneAvailable'),
      ('Cass', 'humanoid', ['RoseofSharonCassidy'], 'bCassHired', 'bCassFired', 'bCassAvailable'),
      ('Veronica', 'humanoid', ['Veronica'], 'bVeronicaHired', 'bVeronicaFired', 'bVeronicaAvailable'),
      ('Lily', 'humanoid', ['Lily'], 'bLilyHired', 'bLilyFired', 'bLilyAvailable'),
      ('EDE', 'critter', ['NVCompanionEdE', 'NVCompanionEdEUpgradeArmor', 'NVCompanionEdEUpgradeWeapons', 'NVCompanionEdEDdisabled'],
       'bEDEHired', 'bEDEFired', 'bEDEAvailable'),
      ('Raul', 'humanoid', ['RaulTejada'], 'RaulHired', 'RaulFired', 'RaulAvailable'),
      ('Arcade', 'humanoid', ['VFSArcadeGannon'], 'ArcadeHired', 'ArcadeFired', 'ArcadeAvailable'),
      ('Rex', 'critter', ['Rex'], 'RexHired', 'RexFired', 'RexAvailable')]),
    ('NVDLC01Followers', 'NVDLC01FollowersQuestScript',
     {'hasFollower': 'bHaveCompanion'},
     [('Dean', 'humanoid', ['NVDLC01Dean'], 'bDeanHired', 'bDeanFired', 'bDeanAvailable'),
      ('Christine', 'humanoid', ['NVDLC01Christine'], 'bChristineHired', 'bChristineFired', 'bChristineAvailable'),
      ('Dog', 'critter', ['NVDLC01Dog'], 'bDogHired', 'bDogFired', 'bDogAvailable')]),
    ('NVDLC02FollowersQuest', 'NVDLC02FollowersQuestSCRIPT',
     {},
     [('FollowsChalk', 'humanoid', ['NVDLC02FollowsChalk'], 'bFollowsChalkHired', 'bFollowsChalkFired', 'bFollowsChalkAvailable'),
      ('WakingCloud', 'humanoid', ['NVDLC02WakingCloud'], 'bWakingCloudHired', 'bWakingCloudFired', 'bWakingCloudAvailable'),
      ('JoshuaGraham', 'humanoid', ['NVDLC02Joshua'], 'bJoshuaGrahamHired', 'bJoshuaGrahamFired', 'bJoshuaGrahamAvailable')]),
]


def fmt(ref):
    p, _, h = ref.rpartition(':')
    return '%s:%s' % (p, h.upper())


def generate():
    forms = json.load(gzip.open(os.path.join(QD, 'forms.json.gz'), 'rt'))
    scripts = {s['edid']: s for s in json.load(gzip.open(os.path.join(QD, 'scripts.json.gz'), 'rt'))}
    by_edid = {}
    for k, v in forms.items():
        if v.get('edid'):
            by_edid.setdefault(v['edid'], []).append((k, v))
    refs_of = {}
    for k, v in forms.items():
        if v.get('sig') in ('ACHR', 'ACRE') and v.get('base'):
            refs_of.setdefault(v['base'], []).append(k)
    out = ['# generated by tools/gen_follower_rules.py from out/questdata; do not edit',
           '# G33: per-owner rewrite of the follower quest variables (vanilla VNPCFollowers + the Dead Money and Honest Hearts follower quests)']
    problems = []
    for qedid, sedid, flags, comps in QUESTS:
        quest = [k for k, v in by_edid.get(qedid, []) if v.get('sig') == 'QUST']
        if len(quest) != 1:
            problems.append('quest %s: %d matches' % (qedid, len(quest)))
            continue
        if sedid not in scripts:
            problems.append('script %s missing' % sedid)
            continue
        idx = {v['name'].lower(): v['idx'] for v in scripts[sedid]['script']['vars']}

        def var(name):
            if name.lower() not in idx:
                problems.append('%s: no variable %s' % (sedid, name))
                return -1
            return idx[name.lower()]
        out.append('quest %s %s' % (fmt(quest[0]), qedid))
        for flag in ('humanoid', 'critter', 'hasFollower', 'current'):
            if flag in flags:
                out.append('flag %s %d' % (flag, var(flags[flag])))
        for name, kind, bases, hired, fired, avail in comps:
            refs = []
            for b in bases:
                for k, v in by_edid.get(b, []):
                    if v.get('sig') in ('NPC_', 'CREA'):
                        refs.append(fmt(k))                       # the base too: harmless, and the only form when no ref is extracted
                        refs += [fmt(r) for r in refs_of.get(k, [])]
            if not refs:
                problems.append('%s: no forms for %s' % (qedid, name))
            out.append('companion %s %s hired=%d fired=%d available=%d refs=%s' % (
                name, kind, var(hired), var(fired), var(avail), ','.join(sorted(set(refs)))))
    return out, problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'plugin', 'dialogue', 'data', 'follower_rules.txt'))
    ap.add_argument('--check', action='store_true', help='compare with the committed file instead of writing')
    a = ap.parse_args()
    lines, problems = generate()
    for p in problems:
        print('PROBLEM', p)
    if problems:
        return 1
    text = '\n'.join(lines) + '\n'
    if a.check:
        same = os.path.exists(a.out) and open(a.out, encoding='utf8').read() == text
        print('follower rules: %s' % ('OK' if same else 'DIFF'))
        return 0 if same else 1
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w', newline='\n') as f:
        f.write(text)
    print('wrote %d companions in %d follower quests to %s' % (sum(1 for l in lines if l.startswith('companion')), sum(1 for l in lines if l.startswith('quest')), a.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
