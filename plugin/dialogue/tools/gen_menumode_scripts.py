#!/usr/bin/env python3
"""Scripts with a `begin MenuMode 1001` block (gap G07), from the ESM extraction in out/questdata.

A MenuMode block only runs on a machine that has a menu of that type open. Menu 1001 is the message box, so a script that shows a box with
ShowMessage and polls GetButtonPressed inside `begin MenuMode 1001` (Fort Caesar's surgery, the AutoDoc, 44 scripts) never gets its block
run on the host while the box is raised to a guest. plugin/hooks_ui mirrors the box on the host for exactly these scripts when [ui]
menumode=mirror. Writes plugin/dialogue/data/menumode_scripts.txt: "<plugin>:<HEXID> <edid>" per script.

Usage: python -I plugin/dialogue/tools/gen_menumode_scripts.py [--out file]
"""
import argparse, gzip, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
QD = os.path.join(ROOT, 'out', 'questdata')
MENU_MESSAGE = 1001
BLOCK = re.compile(r'(?im)^\s*begin\s+menumode\s*(\d*)')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'plugin', 'dialogue', 'data', 'menumode_scripts.txt'))
    a = ap.parse_args()
    rows = []
    for s in json.load(gzip.open(os.path.join(QD, 'scripts.json.gz'), 'rt')):
        src = (s.get('script') or {}).get('source') or ''
        ids = sorted({int(m.group(1)) for m in BLOCK.finditer(src) if m.group(1)})
        if MENU_MESSAGE in ids and s.get('ref'):
            p, _, h = s['ref'].rpartition(':')
            rows.append(('%s:%s' % (p, h.upper()), s['edid']))
    rows.sort()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w', newline='\n') as f:
        f.write('# generated by tools/gen_menumode_scripts.py from out/questdata; do not edit. Scripts with a `begin MenuMode 1001` block (G07).\n')
        for ref, edid in rows:
            f.write('%s %s\n' % (ref, edid))
    print('wrote %d scripts with a MenuMode 1001 block to %s' % (len(rows), a.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
