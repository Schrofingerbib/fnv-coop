#!/usr/bin/env python3
"""Classify the companion dialogue topics from the ESM data (L3 outputs) and write
plugin/dialogue/data/companion_topics.txt, read at runtime by fnvcoop_dlg::loadOwnerOnlyTopics.

Classes (one line each: "<class> <plugin>:<HEXID> <prompt>"):
  ownerOnly  player-prompted command topic of a follower quest (wait, follow distance, trade, tactics, dismiss...)
  recruit    topic whose INFOs run `SetPlayerTeammate 1` (hiring); anyone may take an unowned companion
Barks (names without a space, e.g. HealthQuarter, PLAYER FIRE WEAPON) are neither: they are NPC speech.

Also verifies the VNPCFollowers variable index table in companions.h against the quest script (--check).
Usage: python -I plugin/dialogue/tools/gen_companion_topics.py [--out file] [--check]
"""
import argparse, gzip, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
QD = os.path.join(ROOT, 'out', 'questdata')
FOLLOWER_QUESTS = ('VNPCFollowers', 'NVDLC01Followers', 'NVDLC02FollowersQuest')
HEADER = os.path.join(ROOT, 'plugin', 'dialogue', 'include', 'fnvcoop_dlg', 'companions.h')


def load():
    forms = json.load(gzip.open(os.path.join(QD, 'forms.json.gz'), 'rt'))
    dials = {d['ref']: d for d in json.load(gzip.open(os.path.join(QD, 'dials.json.gz'), 'rt'))}
    infos = [json.loads(l) for l in gzip.open(os.path.join(QD, 'infos.jsonl.gz'), 'rt', encoding='utf8')]
    return forms, dials, infos


def classify():
    forms, dials, infos = load()
    qrefs = {k for k, v in forms.items() if v.get('sig') == 'QUST' and v.get('edid') in FOLLOWER_QUESTS}
    by_topic = {}
    for r in infos:
        if r['quest'] in qrefs and r['type'] == 'topic':
            by_topic.setdefault(r['topic'], []).append(r)
    rows = []
    for t, rs in by_topic.items():
        name = (dials.get(t) or {}).get('name') or ''
        if ' ' not in name or name.upper().startswith('PLAYER '):
            continue  # bark / event topic
        recruit = any(re.search(r'(?i)setplayerteammate\s+1', (r[k] or {}).get('source') or '') for r in rs for k in ('begin', 'end'))
        rows.append(('recruit' if recruit else 'ownerOnly', t, name))
    rows.sort(key=lambda x: (x[0], x[1]))
    return rows


def check_vars():
    """companions.h vnpc::kCompanions / kHumanoidInParty... must match the VNPCFollowers quest script var table."""
    scr = json.load(gzip.open(os.path.join(QD, 'scripts.json.gz'), 'rt'))
    s = [x for x in scr if x['edid'] == 'VNPCFollowersQuestSCRIPT'][0]['script']
    idx = {v['name']: v['idx'] for v in s['vars']}
    src = open(HEADER).read()
    problems = []
    for name, want in (('bHumanoidInParty', 'kHumanoidInParty'), ('bCritterInParty', 'kCritterInParty'),
                       ('bPlayerHasFollower', 'kHasFollower'), ('nCurrentFollowers', 'kCurrentFollowers')):
        m = re.search(want + r'\s*=\s*(\d+)', src)
        if not m or int(m.group(1)) != idx[name]:
            problems.append('%s: header %s, script %s' % (name, m and m.group(1), idx[name]))
    # {"Boone", 6, 7, 8, ...} = hired, fired, available
    pat = {'Boone': 'Boone', 'Cass': 'Cass', 'Veronica': 'Veronica', 'Lily': 'Lily', 'EDE': 'EDE', 'Raul': 'Raul',
           'Arcade': 'Arcade', 'Rex': 'Rex'}
    for m in re.finditer(r'\{"(\w+)",\s*(\d+),\s*(\d+),\s*(\d+),', src):
        n, hired, fired, avail = m.group(1), int(m.group(2)), int(m.group(3)), int(m.group(4))
        for suffix, got in (('Hired', hired), ('Fired', fired), ('Available', avail)):
            cands = [k for k in idx if k.lower().replace('b', '', 1) == (pat[n] + suffix).lower() or k.lower() == (pat[n] + suffix).lower()]
            if not cands:
                problems.append('no script var for %s%s' % (n, suffix))
            elif idx[cands[0]] != got:
                problems.append('%s%s: header %d, script %d' % (n, suffix, got, idx[cands[0]]))
    return problems


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'plugin', 'dialogue', 'data', 'companion_topics.txt'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if a.check:
        p = check_vars()
        for x in p:
            print('MISMATCH', x)
        print('follower vars: %s' % ('OK' if not p else 'MISMATCH'))
        return 1 if p else 0
    rows = classify()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w', newline='\n') as f:
        f.write('# generated by tools/gen_companion_topics.py from out/questdata; do not edit\n')
        for cls, t, name in rows:
            f.write('%s %s %s\n' % (cls, t, name))
    print('wrote %d topics (%d ownerOnly, %d recruit) to %s' % (len(rows), sum(r[0] == 'ownerOnly' for r in rows),
                                                                  sum(r[0] == 'recruit' for r in rows), a.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
