#!/usr/bin/env python3
"""Per-player dialogue data from the ESM extraction (out/questdata), written to plugin/dialogue/data/:

  sayonce_per_player.txt   owner decision D11: say-once lines are shared by the party EXCEPT these, which stay available to every player
                           "speech <plugin>:<HEXID>"   Speech-XP line: a say-once INFO gated on Speech (skill_perk is the Speech AVIF or a
                                                        GetActorValue 43 condition on the player) whose result script runs RewardXP
                           "trainer <plugin>:<HEXID>"  trainer line: a say-once INFO whose result script runs player.AddPerk and says
                                                        taught / trained / teach (Ranger Takedown, Orion...)
  info_facts.txt           the player-private facts each INFO's conditions and result scripts read ("<plugin>:<HEXID> kind=what,..."):
                           av=<AV code>  item=<plugin>:<HEXID>  perk=<plugin>:<HEXID>  equip=<plugin>:<HEXID>
                           The initiator machine evaluates them for its own player and ships them in Pick.facts, so the host can
                           answer player.GetAV / GetItemCount / HasPerk / GetEquipped in the result script as the initiator.

Usage: python -I plugin/dialogue/tools/gen_player_data.py [--outdir DIR]
"""
import argparse, gzip, json, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
QD = os.path.join(ROOT, 'out', 'questdata')
SPEECH_AV = 43
KINDS = {'GetActorValue': 'av', 'GetBaseActorValue': 'av', 'GetPermanentActorValue': 'av', 'GetItemCount': 'item', 'HasPerk': 'perk',
         'GetEquipped': 'equip'}
SCRIPT_READS = [(re.compile(r'(?i)\bplayer\.getitemcount\s+([A-Za-z_][\w]*)'), 'item'),
                (re.compile(r'(?i)\bplayer\.hasperk\s+([A-Za-z_][\w]*)'), 'perk'),
                (re.compile(r'(?i)\bplayer\.getequipped\s+([A-Za-z_][\w]*)'), 'equip')]
TRAINER = re.compile(r'(?i)taught|trained|teach|\btrain')


def load():
    rows = [json.loads(l) for l in gzip.open(os.path.join(QD, 'infos.jsonl.gz'), 'rt', encoding='utf8')]
    forms = json.load(gzip.open(os.path.join(QD, 'forms.json.gz'), 'rt'))
    return rows, forms


def src(r):
    return ((r.get('begin') or {}).get('source') or '') + '\n' + ((r.get('end') or {}).get('source') or '')


def fmt(ref):
    p, _, h = ref.rpartition(':')
    return '%s:%s' % (p, h.upper())


def sayonce(rows, forms):
    speech_avif = None
    cnt = {}
    for r in rows:
        if 'say_once' in r['flags'] and r.get('skill_perk'):
            cnt[r['skill_perk']] = cnt.get(r['skill_perk'], 0) + 1
    out = []
    for r in rows:
        if 'say_once' not in r['flags']:
            continue
        s = src(r)
        speech = any(c['run_on'] == 'target' and c['func'] == 'GetActorValue' and c['p1'] == SPEECH_AV for c in r['conditions'])
        if re.search(r'(?i)\brewardxp\b', s) and (speech or r.get('speech_challenge')):
            out.append(('speech', fmt(r['ref'])))
        elif re.search(r'(?i)\bplayer\.addperk\b', s) and TRAINER.search(s + ' ' + ' '.join(x.get('text', '') for x in r['responses'])):
            out.append(('trainer', fmt(r['ref'])))
    return sorted(set(out), key=lambda x: (x[0], x[1]))


def facts(rows, forms):
    by_edid = {}
    for k, v in forms.items():
        e = v.get('edid')
        if e and v.get('sig') not in ('REFR', 'ACHR', 'ACRE'):
            by_edid.setdefault(e.lower(), k)
    out = {}
    for r in rows:
        fs = []
        for c in r['conditions']:
            kind = KINDS.get(c['func'])
            if not kind or c['run_on'] != 'target':
                continue
            p1 = c['p1']
            if kind == 'av':
                if isinstance(p1, int):
                    fs.append('av=%d' % p1)
            elif isinstance(p1, str) and ':' in p1:
                fs.append('%s=%s' % (kind, fmt(p1)))
        s = src(r)
        for rx, kind in SCRIPT_READS:
            for m in rx.finditer(s):
                ref = by_edid.get(m.group(1).lower())
                if ref:
                    fs.append('%s=%s' % (kind, fmt(ref)))
        fs = sorted(set(fs))
        if fs:
            out[fmt(r['ref'])] = fs[:64]
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--outdir', default=os.path.join(ROOT, 'plugin', 'dialogue', 'data'))
    a = ap.parse_args()
    rows, forms = load()
    so = sayonce(rows, forms)
    fa = facts(rows, forms)
    os.makedirs(a.outdir, exist_ok=True)
    with open(os.path.join(a.outdir, 'sayonce_per_player.txt'), 'w', newline='\n') as f:
        f.write('# generated by tools/gen_player_data.py from out/questdata; do not edit. D11: say-once is shared except these lines.\n')
        for k, ref in so:
            f.write('%s %s\n' % (k, ref))
    with open(os.path.join(a.outdir, 'info_facts.txt'), 'w', newline='\n') as f:
        f.write('# generated by tools/gen_player_data.py from out/questdata; do not edit\n')
        for ref in sorted(fa):
            f.write('%s %s\n' % (ref, ','.join(fa[ref])))
    print('wrote %d per-player say-once lines (%d speech, %d trainer) and the facts of %d INFOs' % (
        len(so), sum(1 for k, _ in so if k == 'speech'), sum(1 for k, _ in so if k == 'trainer'), len(fa)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
