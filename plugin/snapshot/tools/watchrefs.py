#!/usr/bin/env python3
"""Build the default watch-ref list consumed by the in-game dumper (SnapshotOptions.watchRefsFile or env
FNVCOOP_WATCHREFS).

  watchrefs.py [-o out/snapshot/watchrefs.txt] [--hostowned out/coverage/hostowned.txt]
               [--m1 out/questdata/m1_goodsprings.json] [--extra FILE ...]

Sources (each optional; a missing file is reported and skipped, never an error):
  * hostowned.txt (L9): '# load order: 00=FalloutNV.esm, 01=...' header + one 8-hex runtime FormID per line
    (mapped to Plugin.esm:XXXXXX); explicit Plugin.esm:XXXXXX tokens are also taken.
  * m1_goodsprings.json (L3): every {"ref": ..., "sig": "REFR"} object anywhere in the file (NPCs, objective
    targets, enable/disable subjects).
Output: sorted, de-duplicated, one ref per line with a '#' header. Exit 2 if NO source yielded any ref.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import snaplib  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
REF_RE = re.compile(r"[^\s:#,\"'\[\]{}()]+\.(?:esm|esp|esl):[0-9A-Fa-f]{6}\b", re.I)


def norm(r):
    plug, _, idx = r.rpartition(":")
    return "%s:%s" % (plug, idx.upper())


def from_text(text):
    return {norm(m.group(0)) for m in REF_RE.finditer(text)}


LO_RE = re.compile(r"([0-9A-Fa-f]{2})=([^\s,=]+\.es[mpl])", re.I)
RAW_RE = re.compile(r"^\s*([0-9A-Fa-f]{8})\s*(?:#.*)?$")


def from_hostowned(text):
    """L9 format: a '# load order: 00=FalloutNV.esm, 01=...' header and one 8-hex runtime FormID per line
    (top byte = load-order index). Lines that are already Plugin.esm:XXXXXX are accepted too."""
    order = {int(m.group(1), 16): m.group(2) for m in LO_RE.finditer(text)}
    out = from_text(text)
    for line in text.splitlines():
        m = RAW_RE.match(line)
        if m:
            fid = int(m.group(1), 16)
            plug = order.get(fid >> 24)
            if plug:
                out.add("%s:%06X" % (plug, fid & 0xFFFFFF))
    return out


def from_m1(doc):
    out = set()

    def walk(x):
        if isinstance(x, dict):
            r = x.get("ref")
            if isinstance(r, str) and x.get("sig") == "REFR" and REF_RE.fullmatch(r):
                out.add(norm(r))
            for v in x.values():
                walk(v)
        elif isinstance(x, list):
            for v in x:
                walk(v)

    walk(doc)
    return out


def collect(hostowned=None, m1=None, extras=()):
    refs, notes = set(), []
    if hostowned:
        if os.path.exists(hostowned):
            with open(hostowned, encoding="utf-8", errors="replace") as f:
                got = from_hostowned(f.read())
            notes.append("hostowned: %d refs (%s)" % (len(got), hostowned))
            refs |= got
        else:
            notes.append("hostowned: MISSING, skipped (%s)" % hostowned)
    if m1:
        if os.path.exists(m1):
            with open(m1, encoding="utf-8") as f:
                got = from_m1(json.load(f))
            notes.append("m1: %d refs (%s)" % (len(got), m1))
            refs |= got
        else:
            notes.append("m1: MISSING, skipped (%s)" % m1)
    for e in extras:
        with open(e, encoding="utf-8", errors="replace") as f:
            got = from_text(f.read())
        notes.append("extra: %d refs (%s)" % (len(got), e))
        refs |= got
    return sorted(refs), notes


def main(argv=None):
    snaplib.setup_console()
    argv = list(sys.argv[1:] if argv is None else argv)
    o = {"-o": os.path.join(ROOT, "out", "snapshot", "watchrefs.txt"),
         "--hostowned": os.path.join(ROOT, "out", "coverage", "hostowned.txt"),
         "--m1": os.path.join(ROOT, "out", "questdata", "m1_goodsprings.json")}
    extras = []
    i = 0
    while i < len(argv):
        if argv[i] == "--extra":
            extras.append(argv[i + 1]); i += 2
        elif argv[i] in o:
            o[argv[i]] = argv[i + 1]; i += 2
        else:
            print(__doc__); return 2
    refs, notes = collect(o["--hostowned"], o["--m1"], extras)
    print("\n".join(notes))
    if not refs:
        print("no refs found in any source; not writing %s" % o["-o"])
        return 2
    os.makedirs(os.path.dirname(os.path.abspath(o["-o"])), exist_ok=True)
    with open(o["-o"], "w", encoding="utf-8", newline="\n") as f:
        f.write("# generated by plugin/snapshot/tools/watchrefs.py - do not edit\n")
        f.write("\n".join(refs) + "\n")
    print("wrote %d refs to %s" % (len(refs), o["-o"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
