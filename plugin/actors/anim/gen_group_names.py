"""Generates / checks plugin/actors/anim/anim_group_names.inc from tools/animcheck/animgroups_table.py (the xNVSE kAnimGroup_* order).

    python -I plugin/actors/anim/gen_group_names.py            write the .inc
    python -I plugin/actors/anim/gen_group_names.py --check    exit 1 when the .inc differs from the table, or the range constants
                                                               in anim_groups.h do not sit on the names they claim
    python -I plugin/actors/anim/gen_group_names.py --check --mutant   (self test) the check must FAIL on a doctored table

That the running game uses the same numbering is NOT measured yet (docs/tools/T7-anim.md "First in-game check").
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent
sys.path.insert(0, str(ROOT / "tools" / "animcheck"))
from animgroups_table import NAMES  # noqa: E402

INC = HERE / "anim_group_names.inc"
HDR = HERE / "anim_groups.h"


def render(names) -> str:
    lines = ["// GENERATED by gen_group_names.py from tools/animcheck/animgroups_table.py. Do not edit.", "// One name per base animation group id (index = id)."]
    for i, n in enumerate(names):
        lines.append(f'"{n}",  // {i}')
    return "\n".join(lines) + "\n"


# (constant in anim_groups.h) -> name expected at that id
EXPECT = {
    "kGroupIdle": "Idle", "kGroupDynamicIdle": "DynamicIdle", "kGroupSpecialIdle": "SpecialIdle", "kGroupForward": "Forward",
    "kGroupFastRight": "FastRight", "kGroupDodgeForward": "DodgeForward", "kGroupDodgeRight": "DodgeRight",
    "kGroupTurnLeft": "TurnLeft", "kGroupTurnRight": "TurnRight", "kGroupAim": "Aim", "kGroupAimISDown": "AimISDown",
    "kGroupHolster": "Holster", "kGroupEquip": "Equip", "kGroupUnequip": "Unequip", "kGroupAttackFirst": "AttackLeft",
    "kGroupAttackLast": "AttackThrow8ISDown", "kGroupCounter": "Counter", "kGroupStomp": "stomp", "kGroupBlockIdle": "BlockIdle",
    "kGroupBlockHit": "BlockHit", "kGroupRecoil": "Recoil", "kGroupReloadFirst": "ReloadWStart", "kGroupReloadLast": "ReloadZ",
    "kGroupJamFirst": "JamA", "kGroupJamLast": "JamZ", "kGroupStagger": "Stagger", "kGroupDeath": "Death", "kGroupTalking": "Talking",
    "kGroupJumpStart": "JumpStart", "kGroupJumpLoop": "JumpLoop", "kGroupJumpLand": "JumpLand",
    "kGroupJumpLoopForward": "JumpLoopForward", "kGroupJumpLandForward": "JumpLandForward", "kGroupLast": "JumpLandRight",
}


def check(names, inc_text: str, hdr_text: str):
    errs = []
    if inc_text != render(names):
        errs.append("anim_group_names.inc differs from tools/animcheck/animgroups_table.py (rerun gen_group_names.py)")
    for const, want in EXPECT.items():
        m = re.search(r"\b" + const + r"\s*=\s*(\d+)", hdr_text)
        if not m:
            errs.append(f"anim_groups.h has no {const}")
            continue
        idx = int(m.group(1))
        if idx >= len(names) or names[idx] != want:
            got = names[idx] if idx < len(names) else "(out of range)"
            errs.append(f"{const} = {idx} is '{got}' in the table, expected '{want}'")
    m = re.search(r"kGroupCount\s*=\s*(\d+)", hdr_text)
    if not m or int(m.group(1)) != len(names):
        errs.append(f"kGroupCount must equal the table size {len(names)}")
    return errs


def main(argv) -> int:
    names = list(NAMES)
    if "--mutant" in argv:   # doctored table: swap two names; the check must notice
        names[223], names[224] = names[224], names[223]
    if "--check" in argv:
        if not INC.exists() or not HDR.exists():
            print("gen_group_names: files missing")
            return 1
        errs = check(names, INC.read_text(encoding="utf-8").replace("\r\n", "\n"), HDR.read_text(encoding="utf-8"))
        for e in errs:
            print("FAIL:", e)
        print("gen_group_names: " + ("FAILED" if errs else f"ok ({len(names)} groups)"))
        return 1 if errs else 0
    INC.write_text(render(names), encoding="utf-8", newline="\n")
    print(f"wrote {INC} ({len(names)} groups)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
