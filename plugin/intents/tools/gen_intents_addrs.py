"""Generate plugin/intents/engine/intents_addrs.h from an REFERENCE FalloutNV.exe 1.4.0.525 (<reference exe>, see
plugin/hooks/tools/re/README.md).

    python -I plugin/intents/tools/gen_intents_addrs.py <fnv_reference.exe> [--check]

Every entry has its address and the first 16 bytes read from the exe. A hook entry also has the stolen length (instruction aligned, checked by
hand against the bytes: see STOLEN_WHY) and its `ret N` (found by scanning the function body for its epilogue, see RET_WHY). A call entry is
never patched; it is pinned so that a different exe build is noticed before the plugin calls into the wrong code.
tests/test_intents_pins.cpp holds a second hand-copied set of the same bytes, so a regenerate that changes a byte fails the build.
"""
import struct
import sys

# name -> (addr, stolen, retBytes, why)
HOOKS = [
    ("CanSaveNow", 0x850FE0, 6, 4,
     "bool __thiscall(saveMgr, bool ignoreMenus): push ebp; mov ebp,esp; sub esp,14h = 6 bytes; the only epilogue is c2 04 00 at +0xF0"),
    ("TerminalEntryRun", 0x501830, 7, 4,
     "void __thiscall(TerminalEntry* this, TESObjectREFR* terminalRef): push ebp; mov ebp,esp; push ecx; mov [ebp-4],ecx = 7 bytes; epilogue c2 04 00 at +0x3C"),
]
# call-only
CALLS = [
    ("MarkScriptEvent", 0x5AC750, "cdecl bool(TESForm* object, BaseExtraList* targetList, UInt32 mask): the engine's script-event raiser (xNVSE ScriptEventList::kEvent_*)"),
    ("QueueUIMessage", 0x7052F0, "cdecl bool(const char* msg, UInt32 emotion, const char* ddsPath, const char* soundName, float time, bool next): HUD message (xNVSE GameAPI.cpp)"),
    ("CloseAllMenusCore", 0x7037E0, "cdecl void(): what the CloseAllMenus command calls (plugin/hooks_ui/ui_addrs.h pins the same address)"),
    ("TopMenuId", 0x714F00, "thiscall UInt32(InterfaceManager*): id of the menu on top of the stack, 0 when none (docs/re/dialogmenu-menus-vats-inventory.md)"),
]
DATA = [
    ("InterfaceManagerPtr", 0x11D8A80),
    ("SaveLoadMgrPtr", 0x11DE134),   # BGSSaveLoadGame*; plugin/main.cpp kSaveLoadMgrPtr, the `this` of CanSaveNow
]
MENU_IDS = [("ContainerMenu", 0x3F0), ("TerminalMenu", 0x421)]


def load(path):
    d = open(path, "rb").read()
    e = struct.unpack_from("<I", d, 0x3C)[0]
    nsec = struct.unpack_from("<H", d, e + 6)[0]
    opt = struct.unpack_from("<H", d, e + 20)[0]
    secs = []
    for i in range(nsec):
        o = e + 24 + opt + i * 40
        vs, va, rs, rp = struct.unpack_from("<IIII", d, o + 8)
        secs.append((va + 0x400000, max(vs, rs), rp))

    def rd(a, n):
        for va, sz, rp in secs:
            if va <= a < va + sz:
                return d[rp + a - va: rp + a - va + n]
        raise KeyError(hex(a))
    return rd


def hexb(b):
    return ", ".join("0x%02x" % x for x in b)


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    rd = load(sys.argv[1])
    out = ["// GENERATED by tools/gen_intents_addrs.py from the reference FalloutNV.exe 1.4.0.525. Do not edit.",
           "// tests/test_intents_pins.cpp pins every row below (a second, hand-checked copy), so a regenerate that changes a byte fails the build.",
           "#pragma once",
           '#include "hook_patch.h"',
           "",
           "namespace nvcoop::intents::addr {",
           "using nvhooks::HookSpec;"]
    for name, a, st, ret, why in HOOKS:
        b = rd(a, 16)
        assert b[:3] == b"\x55\x8b\xec", name
        out.append("// %s" % why)
        out.append('inline constexpr HookSpec %s = {"%s", 0x%XU, {%s}, 16, %d, %d};' % (name, name, a, hexb(b), st, ret))
    out.append("")
    out.append("struct CallSpec { const char* name; unsigned addr; unsigned char bytes[16]; };")
    for name, a, why in CALLS:
        out.append("// %s" % why)
        out.append('inline constexpr CallSpec %s = {"%s", 0x%XU, {%s}};' % (name, name, a, hexb(rd(a, 16))))
    out.append("")
    for name, a in DATA:
        out.append("inline constexpr unsigned %s = 0x%X;" % (name, a))
    for name, v in MENU_IDS:
        out.append("inline constexpr unsigned k%s = 0x%X;" % (name, v))
    out.append("")
    out.append("inline constexpr const HookSpec* kAllHooks[] = {" + ", ".join("&" + h[0] for h in HOOKS) + "};")
    out.append("inline constexpr const CallSpec* kAllCalls[] = {" + ", ".join("&" + c[0] for c in CALLS) + "};")
    out.append("}  // namespace nvcoop::intents::addr")
    text = "\n".join(out) + "\n"
    target = sys.argv[0].replace("\\", "/").rsplit("/tools/", 1)[0] + "/engine/intents_addrs.h"
    if "--check" in sys.argv:
        same = open(target).read() == text
        print("OK" if same else "DIFF: engine/intents_addrs.h differs from what this generator writes")
        sys.exit(0 if same else 1)
    open(target, "w", newline="\n").write(text)
    print("wrote", target)


main()
