"""Generates plugin/hooks/data/guest_objvars.inc: the shared QUEST variables that object / NPC / magic-effect scripts write inline.

A script of the game says `set VMS16.nGangerDeathCount to VMS16.nGangerDeathCount + 1` in a ganger's OnDeath block. That store is done by the
script interpreter itself: no function to detour, so the guest suppression of mutators (suppress_policy.h rule 3) cannot drop it, and the
guest counts on its own while the host does too. The host is authoritative for quest variables, so on a guest those scripts run inside a
rollback bracket (guest_objvars.h) that puts the written variables back. This file is the list of (script -> quest variable) it needs.

Source: out/questdata/effects.json.gz (unmodeled SetQuestVar lines of every non-quest script block) + out/questdata/quests.json
(quest EDID -> form). Quests on the GuestLocalRun list keep their per-machine variables and are left out.
Run: python -I plugin/hooks/tools/gen_guest_objvars.py          (rewrites the .inc)
     python -I plugin/hooks/tools/gen_guest_objvars.py --check  (exit 1 if the .inc differs from what the data gives; 0 when out/questdata is absent)
"""
import gzip
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
OUT = os.path.join(ROOT, 'plugin', 'hooks', 'data', 'guest_objvars.inc')
SET_RX = re.compile(r'^\s*set\s+([A-Za-z0-9_]+)\.([A-Za-z0-9_]+)\s+to\b', re.I)


def split_ref(ref):
    plugin, _, hexid = ref.rpartition(':')
    return plugin.lower(), int(hexid, 16)


def build():
    base = os.path.join(ROOT, 'out', 'questdata')
    eff = json.load(gzip.open(os.path.join(base, 'effects.json.gz')))
    quests = json.load(open(os.path.join(base, 'quests.json'), encoding='utf-8'))['quests']
    by_edid = {q['edid'].lower(): q['ref'] for q in quests if q.get('edid') and q.get('ref')}
    local = json.load(open(os.path.join(ROOT, 'plugin', 'hooks', 'data', 'guest_local_run.json'), encoding='utf-8'))
    local_edids = {s['quest'].lower() for s in local['scripts']}
    rows = set()
    stats = {'blocks': 0, 'localQuestSkipped': 0, 'notQuest': 0}
    for b in eff['blocks']:
        if b['owner'] == 'quest':
            continue
        for u in b['unmodeled']:
            if u['fn'] != 'SetQuestVar':
                continue
            m = SET_RX.match(u['text'])
            if not m:
                continue
            edid = m.group(1).lower()
            if edid not in by_edid:
                stats['notQuest'] += 1   # a reference variable (`set SomeTriggerREF.bX to 1`): not a quest, not shared quest state
                continue
            if edid in local_edids:
                stats['localQuestSkipped'] += 1
                continue
            sp, sid = split_ref(b['script'])
            qp, qid = split_ref(by_edid[edid])
            rows.add((sp, sid, qp, qid, m.group(2).lower()))
    return sorted(rows), stats


def render(rows):
    out = ['// generated by plugin/hooks/tools/gen_guest_objvars.py from out/questdata - do not edit',
           '// {script plugin, script local id, quest plugin, quest local id, quest variable (lower case)}; sorted by script',
           '// rows: %d, scripts: %d, quests: %d' % (len(rows), len({(r[0], r[1]) for r in rows}), len({(r[2], r[3]) for r in rows}))]
    for sp, sid, qp, qid, var in rows:
        out.append('{"%s", 0x%06X, "%s", 0x%06X, "%s"},' % (sp, sid, qp, qid, var))
    return '\n'.join(out) + '\n'


def main():
    check = '--check' in sys.argv
    if not os.path.isfile(os.path.join(ROOT, 'out', 'questdata', 'effects.json.gz')):
        print('out/questdata is missing: nothing to %s' % ('check' if check else 'generate'))
        return 0 if check else 2
    rows, stats = build()
    text = render(rows)
    if check:
        have = open(OUT, encoding='utf-8', newline='').read().replace('\r\n', '\n') if os.path.isfile(OUT) else ''
        if have != text:
            print('guest_objvars.inc is stale: run python -I plugin/hooks/tools/gen_guest_objvars.py')
            return 1
        print('guest_objvars.inc is current (%d rows)' % len(rows))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d rows, %s' % (OUT, len(rows), stats))
    return 0


sys.exit(main())
