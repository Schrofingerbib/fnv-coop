#!/usr/bin/env python3
"""Regenerates plugin/hooks/story_addrs.h from tests/story_prologues_dump.txt.

The dump lines come from the REFERENCE FalloutNV.exe 1.4.0.525 (the same image and the same rizin method as
tools/re/pro.py): `Cmd_<LongName> <execute address> stolen=<n> bytes16=<hex> first=[...]`. The execute address of every command is the
`execute` column of the engine command table (tools/re/command_table.json). Every function here is a script command handler,
`bool __cdecl(pi, sd, thisObj, contObj, script, ev, res, opc)`, so retBytes is 0 (the shared Cmd_Execute type).

Usage: python -I plugin/hooks/tools/gen_story_addrs.py            (rewrites story_addrs.h)
       python -I plugin/hooks/tools/gen_story_addrs.py --check    (exit 1 when the header is stale)
"""
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
DUMP = HERE / 'tests' / 'story_prologues_dump.txt'
OUT = HERE / 'story_addrs.h'


def render():
    rows = []
    for ln in DUMP.read_text().splitlines():
        m = re.match(r'(\S+)\s+(0x[0-9a-f]+) stolen=(\d+) bytes16=([0-9a-f]{32})', ln)
        if m:
            rows.append(m.groups())
    out = ['// GENERATED by tools/gen_story_addrs.py from tests/story_prologues_dump.txt -- do not edit by hand.',
           '// Script command handlers of FalloutNV.exe 1.4.0.525 used by the story-capture hooks (ref_ops.h). Source: the engine command table',
           '// (tools/re/command_table.json, `execute` column) + the first 16 bytes of the reference image. conf V (handler of a named command).',
           '#pragma once',
           '#include "hook_patch.h"',
           'namespace nvhooks { namespace story_addr {']
    for name, addr, stolen, b in rows:
        bs = ', '.join('0x' + b[i:i + 2] for i in range(0, 32, 2))
        out.append(f'inline constexpr HookSpec {name} = {{"{name}", {addr}u, {{{bs}}}, 16, {int(stolen)}, 0}};')
    out.append('inline constexpr const HookSpec* kAll[] = {')
    for name, *_ in rows:
        out.append(f'    &{name},')
    out.append('};')
    out.append('}}  // namespace nvhooks::story_addr')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = render()
    if '--check' in sys.argv:
        cur = OUT.read_text() if OUT.exists() else ''
        sys.exit(0 if cur.replace('\r\n', '\n') == text else 1)
    OUT.write_text(text, newline='\n')
    print('wrote', OUT, len(text.splitlines()), 'lines')
