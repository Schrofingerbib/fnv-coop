#!/usr/bin/env python3
"""Writes two files from the REFERENCE FalloutNV.exe 1.4.0.525 (<reference exe>, not in git):

  plugin/hooks/data/story_cmd_params.json  for every RefCommand op (synccore/include/fnvcoop/refop.h) the engine's own description of the command
      it hooks: execute handler, `needsParent`, and the parameter list (ParamInfo type id + optional flag) read from the command table
      (struct CommandInfo, stride 0x38 in the table at 0x118E8E0, see tools/re/cmds.py).
  plugin/hooks/story_animgroups.h          the engine's animation group names (g_animGroupInfos, 0x11977D8, stride 0x24, 245 entries): the value
      ExtractArgs returns for an AnimationGroup parameter (PlayGroup) is the index into that table, and the console takes the name.

The unit tests (tests/test_story.cpp) check ref_ops.cpp against these files, so a wrong argument layout fails in seconds without a game.
Run:  python -I plugin/hooks/tools/gen_story_params.py [--check]
"""
import json
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[3]
EXE = ROOT / 'out' / 'L5' / 're' / 'fnv_reference.exe'
TABLE = ROOT / 'plugin' / 'hooks' / 'tools' / 're' / 'command_table.json'
REFOP = ROOT / 'synccore' / 'include' / 'fnvcoop' / 'refop.h'
OUT = ROOT / 'plugin' / 'hooks' / 'data' / 'story_cmd_params.json'
ANIM_OUT = ROOT / 'plugin' / 'hooks' / 'story_animgroups.h'
ANIM_TABLE = 0x11977D8   # g_animGroupInfos (xNVSE GameAPI.cpp, FalloutNV 1.4.0.525)
ANIM_STRIDE, ANIM_COUNT = 0x24, 245
CRIT_TABLE = 0x119BBB0   # g_criticalStageNames (xNVSE GameAPI.cpp): 5 pointers; entry 0 is not a readable string in the image ("None" in the GECK)


def op_names():
    txt = REFOP.read_text()
    names = re.findall(r'(?:FNV_RO_[ES]\(kOp\w+, |\{kOp\w+, )"(\w+)"', txt)
    return [n for n in names if n != 'None']


def exe_image():
    d = EXE.read_bytes()
    pe = struct.unpack_from('<I', d, 0x3c)[0]
    nsec = struct.unpack_from('<H', d, pe + 6)[0]
    opt = struct.unpack_from('<H', d, pe + 20)[0]
    secs = []
    off = pe + 24 + opt
    for _ in range(nsec):
        vs, va, rs, rp = struct.unpack_from('<IIII', d, off + 8)
        secs.append((va + 0x400000, vs, rp, rs))
        off += 40

    def v2o(v):
        for va, vs, rp, rs in secs:
            if va <= v < va + max(vs, rs):
                return rp + v - va
        raise ValueError(hex(v))

    def u32(v):
        return struct.unpack_from('<I', d, v2o(v))[0]

    def u16(v):
        return struct.unpack_from('<H', d, v2o(v))[0]

    def cstr(v):
        o = v2o(v)
        return d[o:d.index(bytes([0]), o)].decode('latin1')

    return u32, u16, cstr


def anim_header():
    u32, _u16, cstr = exe_image()
    names = [cstr(u32(ANIM_TABLE + ANIM_STRIDE * i)) for i in range(ANIM_COUNT)]
    out = ['// GENERATED by tools/gen_story_params.py from the reference FalloutNV.exe 1.4.0.525 -- do not edit by hand.',
           '// The engine animation group names, g_animGroupInfos (0x11977D8, stride 0x24, 245 entries): the value ExtractArgs returns for an',
           '// AnimationGroup parameter (PlayGroup) is the index into this table, and the console takes the name. Matches the compiler loop in',
           '// xNVSE GameAPI.cpp (kParamType_AnimationGroup searches g_animGroupInfos[0..244] by name).',
           '#pragma once',
           'namespace nvhooks {',
           'inline constexpr int kAnimGroupCount = %d;' % ANIM_COUNT,
           'inline constexpr const char* const kAnimGroupNames[kAnimGroupCount] = {']
    for i in range(0, ANIM_COUNT, 6):
        out.append('    ' + ', '.join('"%s"' % n for n in names[i:i + 6]) + ',')
    out += ['};']
    crit = ['None'] + [cstr(u32(CRIT_TABLE + 4 * i)) for i in range(1, 5)]
    out += ['// g_criticalStageNames (0x119BBB0, 5 entries): the value ExtractArgs returns for a CriticalStage parameter (SetCriticalStage). Entries 1..4 are read',
            '// from the image; entry 0 is the GECK name of the first stage.',
            'inline constexpr int kCriticalStageCount = 5;',
            'inline constexpr const char* const kCriticalStageNames[kCriticalStageCount] = {' + ', '.join('"%s"' % n for n in crit) + '};',
            '}  // namespace nvhooks']
    return '\n'.join(out) + '\n'


def build():
    u32, u16, _cstr = exe_image()
    ct = json.loads(TABLE.read_text())
    out = {}
    for n in op_names():
        e = ct[n]
        ent = int(e[4], 16)
        np_ = u16(ent + 0x12)
        pp = u32(ent + 0x14)
        params = [[u32(pp + 12 * i + 4), u32(pp + 12 * i + 8)] for i in range(np_)]
        out[n] = {'execute': e[1], 'parent': u16(ent + 0x10), 'params': params}
    return out


if __name__ == '__main__':
    data = build()
    text = json.dumps(data, indent=1, sort_keys=True) + '\n'
    anim = anim_header()
    if '--check' in sys.argv:
        same = (OUT.exists() and OUT.read_text().replace('\r\n', '\n') == text and ANIM_OUT.exists() and
                ANIM_OUT.read_text().replace('\r\n', '\n') == anim)
        sys.exit(0 if same else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, newline='\n')
    ANIM_OUT.write_text(anim, newline='\n')
    print('wrote', OUT, len(data), 'commands;', ANIM_OUT, ANIM_COUNT, 'animation groups')
