    L += ['## 1. Inventory', '', '| quest | INFOs | distinct topics | scripted INFOs | goodbye | say_once | skill/perk gated | types |', '|---|---:|---:|---:|---:|---:|---:|---|']
    skills = collections.Counter()
    for q in dq:
        infos = data.infos_by_quest.get(q['ref'], [])
        fl = collections.Counter(f for i in infos for f in i.get('flags', []))
        ty = collections.Counter(i.get('type') for i in infos)
