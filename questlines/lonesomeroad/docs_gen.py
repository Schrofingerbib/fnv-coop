def _fn(g, name):
    return next((f for f in g['functions'] if f['fn'] == name), None)


def _locs(f, n=3, only_gap=False):
    if not f:
        return '-'
    ls = [l for l in f['locations'] if (not only_gap or l['status'] in ('partial', 'missing')) and 'TEST' not in l['script']]
    ls.sort(key=lambda l: (not l.get('reached', True), l['kind'] not in ('stage', 'info', 'quest'), l['script'], l['line']))
    return '; '.join('`%s:%d`' % (l['script'], l['line']) for l in ls[:n]) or '-'


