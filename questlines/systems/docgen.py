# ---------------------------------------------------------------- gaps.md
def render_gaps(gaps, cen):
    c = gaps['counts']
    L = ['# Gaps: script functions in the `systems` scope', '',
         'Scope scripts: ' + gaps['scope_scripts'] + '. Only calls whose L5 status is not `supported` are listed (%d calls). '
         'Severity: **blocker** = companion / spawn / cinematic / save / ending / essential hazards or level-4 player calls; **major** = player-targeted rewards, perks, factions, '
         'teleports, menus, kills, timers; **minor/low** = remaining partial/missing; **info** = local presentation.' % c['unsupported_calls'], '',
         'By severity: ' + ', '.join('%s %d' % kv for kv in sorted(c['by_severity'].items(), key=lambda x: -x[1])),
         'By status: ' + ', '.join('%s %d' % kv for kv in c['by_status'].items()), '',
         '## Functions (worst severity per function)', '',
         table(['function', 'calls', 'quests', 'Effect', 'L5', 'severity', 'hazards'],
               [[r['fn'], r['count'], r['quests'], r['effect'] or '-', r['l5_status'], r['severity'], ','.join(r['hazards']) or '-']
                for r in gaps['by_function']]), '',
         '## Exact locations (blocker + major, max 6 per function and quest; all locations are in gaps.json `items`)', '']
    seen = collections.Counter()
    rows = []
    for it in gaps['items']:
        if it['severity'] not in ('blocker', 'major'):
            continue
        key = (it['fn'], it['quest'])
        seen[key] += 1
        if seen[key] > 6:
            continue
        rows.append([it['severity'], it['fn'], it['quest'], '%s:%s' % (it['where'], it['line']), it['policy'], it['text'][:70]])
    rows.sort(key=lambda r: (r[0] != 'blocker', r[1], r[2]))
    L.append(table(['sev', 'fn', 'quest', 'where:line', 'policy', 'text'], rows[:700]))
    if len(rows) > 700:
        L.append('')
        L.append('(%d more rows in gaps.json)' % (len(rows) - 700))
    return '\n'.join(L) + '\n'


