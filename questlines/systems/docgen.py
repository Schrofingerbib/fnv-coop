# ---------------------------------------------------------------- dialogue analysis
def dialogue_stats(recs):
    by_ref = {r['ref']: r for r in recs}
    with gzip.open(os.path.join(qlib.QD, 'dials.json.gz'), 'rt', encoding='utf-8') as f:
        dials = {x['ref']: x for x in json.load(f)}
    qref = {q['ref']: q['edid'] for q in qlib.quests()}
    forms = qlib.forms()
    refn = qlib.refnames()
    per = collections.defaultdict(lambda: collections.Counter())
    conv = []
    for i in qlib.infos():
        r = by_ref.get(i['quest'])
        if not r:
            continue
        e = r['edid']
        per[e]['infos'] += 1
        if i.get('skill_perk'):
            per[e]['skill_perk'] += 1
        if i.get('speech_challenge'):
            per[e]['speech_challenge'] += 1
        eff = collections.Counter()
        for k in ('begin', 'end'):
            s = i.get(k)
            if not s:
                continue
            for _ln, fn, subj, args, _line in qlib.statements(s['source']):
                c = census.canonical(fn) if fn.lower() != 'set' else 'set'
                eff[c] += 1
        if eff:
            per[e]['with_result'] += 1
        tags = []
        if eff['setstage']:
            tags.append('branches-quest')
        if eff['setplayerteammate']:
            tags.append('companion')
        if eff['addtofaction'] or eff['removefromfaction'] or eff['addreputation'] or eff['setfactionrank'] or eff['setreputation']:
            tags.append('faction/rep')
        if eff['rewardkarma']:
            tags.append('karma')
        if i.get('skill_perk') or i.get('speech_challenge'):
            tags.append('skill/speech-check')
        if eff['showbartermenu'] or eff['showcaravanmenu'] or eff['showrepairmenu'] or eff['showrecipemenu']:
            tags.append('service-menu')
        if eff['startcombat'] or eff['killactor']:
            tags.append('combat/kill')
        if tags:
            d = dials.get(i['topic'], {})
            sp = None
            conv.append({'info': i['formid'], 'quest': e, 'topic': d.get('edid'), 'type': i['type'], 'tags': tags,
                         'score': eff['setstage'] * 3 + eff['setplayerteammate'] * 5 + eff['addtofaction'] + eff['addreputation']
                         + eff['rewardkarma'] * 2 + (2 if i.get('skill_perk') else 0) + (3 if i.get('speech_challenge') else 0)
                         + eff['startcombat'] + eff['killactor'],
                         'line': (i['responses'][0]['text'][:80] if i['responses'] else ''),
                         'effects': {k: v for k, v in eff.items() if k in ('setstage', 'setplayerteammate', 'addtofaction', 'removefromfaction',
                                                                         'addreputation', 'rewardkarma', 'startcombat', 'killactor', 'addperk',
                                                                         'rewardxp', 'additem', 'removeitem')}})
    conv.sort(key=lambda c: -c['score'])
    return per, conv


def render_dialogue(recs, comp):
    per, conv = dialogue_stats(recs)
    tot_inf = sum(c['infos'] for c in per.values())
    L = ['# Key conversations (systems scope, L8 spec style)', '',
         'Source: INFO records of the %d in-scope quests (%d INFOs with a quest owner in scope). Spec vocabulary follows `docs/dialogue-design.md` '
         '(initiator = the player who opened the DialogMenu; begin/end scripts run on the host under effect capture; skill/speech gates are evaluated for the initiator).' % (len(recs), tot_inf), '',
         '## 1. Where the checks and branches are (per quest)', '',
         table(['quest', 'type', 'INFOs', 'with result script', 'skill/perk gate', 'speech challenge'],
               [[e, next(r['type'] for r in recs if r['edid'] == e), c['infos'], c['with_result'], c['skill_perk'], c['speech_challenge']]
                for e, c in sorted(per.items(), key=lambda kv: -kv[1]['infos'])[:40]]), '',
         '## 2. Companion recruitment / dismissal conversations (INFO ids)', '']
    for n, c in comp['companions'].items():
        ev = c['evidence']
        L.append('### %s (perk %s, flag %s)' % (n, list(c['recruit_perk_on_player'])[0], c['hired_flag_in_VNPCFollowers']))
        L.append('- spec: `Recruit{npc=%s, initiator=owner, effects=[CompanionOwner, SetPerk(owner,%s), SetFactionRank(Follower/Teammate faction), SetScriptVar(%s)]}`'
                 % (n, list(c['recruit_perk_on_player'])[0], c['hired_flag_in_VNPCFollowers']))
        for k, lab in (('recruit', 'recruit'), ('dismiss', 'dismiss'), ('perk_add', 'perk add')):
            rows = ev[k][:5]
            if rows:
                L.append('- %s INFOs: ' % lab + ', '.join('%s (%s/%s)' % (e['info'], e['quest'], e['topic']) for e in rows))
        L.append('')
    L += ['## 3. Conversations that branch a questline or change faction/karma (top 40 by weight)', '',
          table(['INFO', 'quest', 'topic', 'type', 'tags', 'effects', 'first line'],
                [[c['info'], c['quest'], c['topic'], c['type'], ','.join(c['tags']), ' '.join('%s:%d' % kv for kv in c['effects'].items()), c['line']]
                 for c in conv[:40]]), '',
          '%d INFOs in scope carry at least one of: quest branch, companion change, faction/rep change, karma, skill/speech gate, service menu, combat.' % len(conv), '',
          '## 4. Where the initiator-picks model breaks', '']
    for t in BREAKS:
        L.append('- ' + t)
    return '\n'.join(L) + '\n'


