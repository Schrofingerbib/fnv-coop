"""Writes internal questline notes (status summary) from the generated JSON and the real test output.

    python -I questlines/act2/write_status.py     # builds the doc, runs run_tests.py, pastes its output into the doc
"""
import json
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[1]
DOC = REPO / 'docs' / 'questlines' / 'act2.md'


def load(name):
    return json.load(open(HERE / name, encoding='utf-8'))


def theme(g, name):
    return next((b for b in g['blockers'] if b['theme'] == name), {'occurrences': 0, 'quests': {}, 'rank': 0})


def render(test_output):
    inv, sw, g, patch = load('inventory.json'), load('sweep.json'), load('gaps.json'), load('rules.patch.json')
    dj = load('dialogue.json')
    s = g['summary']
    t = inv['totals']
    sev = s['unsupported_occurrences_by_severity']
    th = lambda n: theme(g, n)   # noqa: E731
    fc = lambda fn: next((f['locations_total'] for f in g['functions'] if f['fn'] == fn and f['kind'] == 'stmt'), 0)   # noqa: E731
    n_add = sum(len(v['add']) for v in patch['quests'].values())
    n_mod = sum(len(v['modify']) for v in patch['quests'].values())
    lines = [
        '# act2 questline status: Ring-a-Ding-Ding and the shared Act 2 quests',
        '',
        'Lane: Q-act2. Slug `act2`. Questline "%s" (docs/quest-policies/main-shared-ring-a-ding-ding-and-act-2.md).' % inv['questline'],
        'Everything below is generated by `python -I questlines/act2/build.py`; the game was not launched, nothing outside `questlines/act2/` '
        'and this file was written.',
        '',
        '## Counts',
        '',
        '| item | value |', '|---|---|',
        '| quests | %d (%s) |' % (t['quests'], ', '.join('%s %d' % kv for kv in sorted(t['tiers'].items()))),
        '| stages | %d (%d entries) |' % (t['stages'], t['stage_entries']),
        '| stages swept (sweep.json) | %d of %d, %d excluded |' % (sw['summary']['stages_swept'], sw['summary']['stages'], sw['summary']['excluded']),
        '| objectives | %d |' % t['objectives'],
        '| INFOs | %d in the 14 quests\' own dialogue containers + %d driver INFOs in other quests; %d carry a co-op tag |' % (
            t['own_infos'], t['driver_infos'], dj['summary']['key_infos']),
        '| script units analysed | %d (%s) |' % (s['units'], ', '.join('%s %d' % kv for kv in sorted(s['units_by_scope'].items()))),
        '| distinct script functions | %d (%s) |' % (s['distinct_functions'], ', '.join('%s %d' % kv for kv in sorted(s['functions_by_status'].items()))),
        '| function occurrences by status | %s |' % ', '.join('%s %d' % kv for kv in sorted(s['occurrences_by_status'].items())),
        '| **gaps** (missing + partial occurrences) by severity | high %d, medium %d, low %d |' % (sev.get('high', 0), sev.get('medium', 0), sev.get('low', 0)),
        '| blocker themes | %d (%d high) |' % (len(g['blockers']), sum(1 for b in g['blockers'] if b['severity'] == 'high')),
        '| rules.patch.json | %d rule additions, %d parameter merges into existing rules, %d new rule kinds and %d parameter-semantics extensions proposed |' % (
            n_add, n_mod, len(patch['new_kinds']), len(patch['param_extensions'])),
        '| dialogue specs | %d (plugin/dialogue scenario schema) |' % len(dj['specs']),
        '',
        '## Deliverables (all in `questlines/act2/`)',
        '',
        '| file | what |', '|---|---|',
        '| `inventory.json` | every quest: stages, objectives (+resolved targets), prerequisites from conditions and the questgraph, dialogue counts, tier |',
        '| `sweep.json` | L7 plan in the m1_goodsprings.json shape + `setup` command lists, `reset_quests`, stage variants and branch guards |',
        '| `gaps.json`, `gaps.md` | every script function -> Effect type + L5 capture/apply status, exact locations, hazard themes |',
        '| `policy_review.md`, `rules.patch.json` | owner-decision audit of rules.json, story-moment tethers, cinematics, reward routing, patch |',
        '| `dialogue.md`, `dialogue.json`, `dialogue_specs/` | key conversations, where initiator-picks breaks, L8-style scenario specs |',
        '| `build.py`, `run_tests.py`, `write_status.py` | generator (deterministic), tests with mutation twins, this status doc |',
        '',
        '## TOP 10 blockers for co-op in this questline (ranked by story impact)',
        '',
        'Counts are unsupported occurrences from `gaps.json` (themes overlap where noted). "Needs" names the missing layer.',
        '',
        '1. **Guest-originated triggers never reach the host scripts** (%d player-event blocks + %d Activate/IsActionRef lines). '
        '`VPlatinumChipSCRIPT begin OnAdd player` runs `SetStage VMQTops 80` + `CompleteAllObjectives VMQTops`, so Ring-a-Ding-Ding completes '
        'only if the *host* player picks the chip up (inferred from the Guest gate design, not yet observed in game); the same holds for the VIP keycard and the Bitter Springs books (OnAdd), the Fort gate, '
        'barge, tent flap and every elevator door (`IsActionRef player`), and 51 `OnHit/OnStartCombat/OnDeath player` blocks (Benny, Kimball, Moore). '
        'Needs: guest-originated trigger intents (L5 design only) and the proposed `GuestEventRelay` rule kind.' % (th('GUEST_EVENT')['occurrences'], th('GUEST_ACTIVATION')['occurrences']),
        '2. **Player-reference reads see only the host player** (%d lines): `GetDistance`, `GetInCell`, `GetInSameCell`, `IsKiller`, `GetAV`, '
        '`GetItemCount` on `player` in the Hoover Dam sniper/guard scripts, quest timers (VMQ03a/b "left the area"), Benny and the Ultra-Luxe doors. '
        'Needs: an engine-side hook that evaluates these over the party (`RulesEngine::reduceCondition` exists but nothing calls it from a script).' % th('PLAYER_REF_COND')['occurrences'],
        '3. **Battle-of-Hoover-Dam starts are single-player sequences** (FortCaesar, FortLucius, VHDColonelMoore, YesManDead): prompt -> '
        '`player.MoveTo` -> companions `MoveTo` -> lock -> autosave. They contain the modal point-of-no-return prompts (%d "VEndGameWarningMsg*" '
        'lines) answered by a single `GetButtonPressed`. Needs: party consent (`ModalChoice`, proposed), PartyWarp in the same transaction, tether first.' % th('POINT_OF_NO_RETURN')['occurrences'],
        '4. **Modal message choices can only be answered on the host** (%d lines: elevator floor menus in the three Lucky 38 elevator scripts, '
        'Fort Caesar/Lucius, Moore, Yes Man, Kimball vertibird, the Ultra-Luxe wine, Watson\'s helmet). Needs: `ShowMessageChoice` routed to the initiator.' % th('MESSAGE_CHOICE')['occurrences'],
        '5. **Cutscene control locks are not captured from scripts** (%d lines, %d Disable + %d Enable): the SetPlayerControls rule has nothing '
        'to fire on, and the applier is one coarse all-controls flag although the scripts use three different masks. Needs: capture of '
        '`Disable/EnablePlayerControls` with mask, per-flag apply.' % (th('CONTROLS')['occurrences'], fc('disableplayercontrols'), fc('enableplayercontrols')),
        '6. **Player teleports are not party-wide** (%d `player.MoveTo` lines: 12 Lucky 38 elevator transfers, 4 battle starts, the Van Graff '
        'warehouse). PartyWarp is inactive without `RulesEngine::Options::playerRef`. Needs: playerRef wiring + the `absent: skip, radius` '
        'extension for free-roam elevators.' % th('TELEPORT')['occurrences'],
        '7. **Forced dialogue has no capture or spectator playback** (%d `SayTo player`/`StartConversation` lines; Silver Rush brawl, Fort audience, '
        'Kimball and Moore speeches, Heck Gunderson arrest). Needs: `ForcedDialogue` capture + L8 playback, and a defined "player" for scenes with no initiator.' % th('FORCED_DIALOGUE')['occurrences'],
        '8. **Fast-travel locks are neither captured nor applied** (%d lines; `EnableFastTravel 0` for the whole Kimball protection/assassination '
        'scenes and the battle starts). A guest who fast-travels away fails the scene for everyone. Needs: `SetFastTravelLock` capture + apply.' % th('FAST_TRAVEL')['occurrences'],
        '9. **Companions and perks** (%d companion lines: `SetPlayerTeammate` %d, `OpenTeammateContainer` %d; %d `AddPerk/RemovePerk` lines: Cassidy recruit, Boone/Cass/Veronica/Arcade freezer '
        'and dismissal): block-only hooks suppress them on guests and record nothing; `player` resolves to the initiator, not the recruiter. '
        'Needs: `CompanionOwner`/`SetPerk` capture + apply routed to the recruiter.' % (
            th('COMPANION')['occurrences'], fc('setplayerteammate'), fc('openteammatecontainer'), th('PERK')['occurrences']),
        '10. **World-state mutations suppressed on guests and never recorded**: door lock/open state (%d lines, mostly the Hoover Dam tower doors '
        'in VMQ03a/b stages), `MarkForDelete` (%d), `PlaceAtMe` spawns (%d: the VMQ04 nuke explosions, the Kimball anti-aircraft and vertibird explosions), player faction '
        'standing/hostility (%d lines) and scripted time skips (%d). Needs: `SetLock`, delete/spawn and faction-relation effects.' % (
            th('DOOR_STATE')['occurrences'], th('DELETE')['occurrences'], th('SPAWN')['occurrences'], th('FACTION_RELATION')['occurrences'],
            th('TIME_SKIP')['occurrences']),
        '',
        'Policy findings that are not engine work (details in `policy_review.md`): `VDialogueLucky38Entrance` (T4) has no rules at all; '
        '%d evidence-backed rule additions are proposed; four quests carry `PartyTether` with an empty cell list; `VMQ04` has no start path in the data '
        '(unknown whether cut content).' % n_add,
        '',
        '## How to use',
        '',
        '- L7: run `sweep.json` like `m1_goodsprings.json` (`quests[].edid/ref/stages[].index/tier`); pass `reset_quests` to `test.quest.reset`; '
        'run quests with `phase: "last"` after the others. `set <hex>.<var> to n` is the only command form unverified in the sweep harness '
        '(`verify: true`).',
        '- L9: apply `rules.patch.json` as described in its `how_to_apply`; the two new kinds and two parameter extensions are proposals (L4 decides).',
        '- L8: `dialogue_specs/*.json` use the plugin/dialogue step vocabulary; `save` is null because no act2 save exists (unknown).',
        '- Re-run `python -I questlines/act2/build.py` after any change to out/questdata, rules.json or policies.json; `run_tests.py` warns when the '
        'committed files were built from different inputs.',
        '',
        '## Test output',
        '',
        '`python -I questlines/act2/run_tests.py`',
        '',
        '```',
        test_output.rstrip(),
        '```',
        '',
    ]
    return '\n'.join(lines)


def main():
    DOC.parent.mkdir(parents=True, exist_ok=True)
    DOC.write_text(render('(pending)'), encoding='utf-8', newline='\n')
    r = subprocess.run([sys.executable, '-I', str(HERE / 'run_tests.py')], capture_output=True, text=True, encoding='utf-8')
    out = r.stdout + (('\n' + r.stderr) if r.stderr.strip() else '')
    DOC.write_text(render(out), encoding='utf-8', newline='\n')
    print(out.splitlines()[-1] if out.strip() else 'no output')
    return r.returncode


if __name__ == '__main__':
    sys.exit(main())
