"""Generate every towns-questline deliverable from out/questdata.  Run: python -I questlines/towns/build.py [--out DIR]

Writes inventory.json, sweep.json, gaps.json, gaps.md, rules.patch.json, dialogue_data.json and dialogue.md (the hand-written
parts of dialogue.md live in dialogue_notes.md and are appended verbatim).  Deterministic: same input, same bytes.
"""
import argparse
import collections
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analysis  # noqa: E402
import fnmap  # noqa: E402
import lib  # noqa: E402
import policy  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))


def dump(path, obj):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(obj, f, indent=1, ensure_ascii=False, sort_keys=False)
        f.write('\n')


def build_all(d):
    inv = analysis.inventory(d)
    sw = analysis.sweep(d, inv)
    items = analysis.gaps(d)
    th = analysis.text_hazards(d)
    summ = analysis.summarize_gaps(items)
    patch = policy.build_patch(d, items)
    dlg = analysis.dialogue(d)
    return inv, sw, items, th, summ, patch, dlg


def md_gaps(items, th, summ, inv):
    L = []
    w = L.append
    w('# Towns questline: script/effect gaps vs synccore + L5')
    w('')
    w('Generated by `questlines/towns/build.py` from `out/questdata` (effects oracle, risk findings, quest/stage/INFO scripts). '
      'Every location is `script (quest stage / INFO / quest-script block / dependent object script) : line`. '
      'Full per-item data (including supported items) is in `gaps.json`.')
    w('')
    w('Sources scanned: the stage, INFO begin/end and quest scripts of %d quests (%d assigned by the policy files / questgraph, %d extra town quests), '
      'plus the object scripts the quests depend on (`dep obj`), plus every player-ref condition the risk classifier found.'
      % (len(inv), sum(1 for i in inv if i['role'] == 'core'), sum(1 for i in inv if i['role'] != 'core')))
    w('')
    w('## Totals')
    w('')
    w('| severity | items |')
    w('|---|---|')
    for k in ('high', 'medium', 'low', 'ok'):
        w('| %s | %d |' % (k if k != 'ok' else 'ok (supported / no sync needed)', summ['by_severity'].get(k, 0)))
    w('')
    w('Status: %s.  Severity rule: **high** = unsupported spawn / companion / essential / teleport / cinematic / control lock / ending / kill-all; '
      '**medium** = other unsupported, or partial with such a hazard, or a player-ref condition (no engine hook evaluates it over the party yet); '
      '**low** = partial without a hazard, host-only AI, cosmetics, tokenizer noise.' % ', '.join('%s %d' % kv for kv in sorted(summ['by_status'].items())))
    w('')
    w('## Effect support used by these quests (synccore Effect -> L5 capture / apply)')
    w('')
    w('| Effect | capture | apply | occurrences | note |')
    w('|---|---|---|---|---|')
    cnt = collections.Counter(i['effect'] for i in items if i['effect'])
    for e, n in cnt.most_common():
        if e in fnmap.EFFECT_STATUS:
            cap, app, note = fnmap.EFFECT_STATUS[e]
            w('| %s | %s | %s | %d | %s |' % (e, cap, app, n, note))
    w('')
    w('## Unsupported / partial functions (grouped; `status` is the worst of capture and apply)')
    w('')
    order = {'high': 0, 'medium': 1, 'low': 2}
    rows = sorted(summ['unsupported'].items(), key=lambda kv: (order[kv[1]['severity']], -kv[1]['count'], kv[0]))
    for sev in ('high', 'medium', 'low'):
        sub = [(k, v) for k, v in rows if v['severity'] == sev]
        if not sub:
            continue
        w('### %s (%d function groups, %d occurrences)' % (sev, len(sub), sum(v['count'] for _, v in sub)))
        w('')
        w('| function -> Effect | n | status | class | hazards | quests | note |')
        w('|---|---|---|---|---|---|---|')
        for k, v in sub:
            w('| `%s` | %d | %s | %s | %s | %s | %s |' % (k, v['count'], v['status'], v['class'], ', '.join(v['hazards']) or '-',
                                                      ', '.join(v['quests'][:6]) + (' +%d' % (len(v['quests']) - 6) if len(v['quests']) > 6 else ''),
                                                      (v['note'] or '').replace('|', '/')[:160]))
        w('')
    w('## Exact locations (high + medium, non-condition)')
    w('')
    for sev in ('high', 'medium'):
        for k, v in [(k, v) for k, v in rows if v['severity'] == sev and v['class'] != 'condition']:
            locs = v['locations']
            shown = ', '.join('%s %s:%s' % (x['quest'], x['script'], x['line']) for x in locs[:10])
            w('- **%s** `%s` x%d: %s%s' % (sev, k, v['count'], shown, ' ... (+%d more in gaps.json)' % (len(locs) - 10) if len(locs) > 10 else ''))
    w('')
    w('## Player-ref conditions (PartyAwareCond candidates; capture/apply = partial: synccore reduction exists, no engine hook)')
    w('')
    for k, v in [(k, v) for k, v in rows if v['class'] == 'condition' and v['severity'] == 'medium']:
        w('- `%s` x%d in %s' % (k, v['count'], ', '.join(v['quests'])))
    w('')
    w('## Co-op hazards by category')
    w('')
    hz = collections.defaultdict(list)
    for i in items:
        if i['status'] == 'supported':
            continue
        for h in i['hazards']:
            hz[h].append(i)
    for t in th:
        hz[t['hazard']].append(dict(t, fn=t['hazard'], status='n/a (text scan)'))
    meaning = [
        ('player-effect', 'player-targeted effects not (fully) captured: RemoveItem/RemoveNote/RemovePerk/AddPerk, control locks, player-ref reads'),
        ('reward', 'rewards routed to every player (RewardAll): AddNote and AddItem/XP with partial apply'),
        ('karma-rep', 'karma / reputation (shared)'), ('faction', 'faction membership / rank / relations (shared)'),
        ('player-faction', 'Player.SetFactionRank / AddToFaction'),
        ('spawn', 'PlaceAtMe spawns'), ('companion', 'SetPlayerTeammate / followers'), ('essential', 'essential/protected flags'),
        ('teleport', 'MoveTo / MoveToMarker on the player (party warp vs activator-only)'),
        ('npc-move', 'MoveTo on NPCs (host-owned; clients follow through NV:MP)'),
        ('cinematic', 'SayTo / StartConversation / DisablePlayerControls / imod scenes'),
        ('control-lock', 'DisablePlayerControls / EnablePlayerControls'),
        ('menu', 'ShowMessage / barter / repair / container menus'), ('ui', 'ShowMap and other per-player UI'),
        ('timer', 'GameDaysPassed / GameHour / GetSecondsPassed waits (time is a shared global)'),
        ('radio', 'radio'), ('ending', 'ending/slideshow'), ('save', 'save control'),
        ('kill-all', '"kill everyone" objectives'), ('quest-var', 'quest/ref variable writes'), ('ai-state', 'AI packages and combat relations (host-owned)'),
    ]
    for h, desc in meaning:
        its = hz.get(h, [])
        w('### %s: %s (%d)' % (h, desc, len(its)))
        if not its:
            w('')
            w('none found.')
            w('')
            continue
        w('')
        by = collections.defaultdict(list)
        for i in its:
            by[i['quest']].append(i)
        for q, xs in sorted(by.items(), key=lambda kv: -len(kv[1]))[:8]:
            shown = '; '.join('%s:%s (%s)' % (x['script'], x.get('line'), x['fn']) for x in xs[:5])
            w('- `%s` x%d: %s%s' % (q, len(xs), shown, ' ...' if len(xs) > 5 else ''))
        if len(by) > 8:
            w('- ... %d more quests (gaps.json)' % (len(by) - 8))
        w('')
    w('## Notes')
    w('')
    w('- The oracle tokenizer reads a few script variables and `if(...)` conditions as commands (`bPlayerDetected`, `bCLBranch`, `bHsuGaveQuest)`, '
      '`if(GetObjectiveDisplayed`); they are listed as class `noise`, severity low.')
    w('- `SetQuestVar` is partial everywhere: quest variables are captured by diffing every quest\'s ScriptEventList, but writes to *reference* script variables '
      '(`set SomeREF.var to ...`) have no hook (L5 round 4, item 11). The towns quests use these heavily (612 SetQuestVar statements).')
    w('- `EnableRef`/`DisableRef` are partial because L5 records only a state *change*; a quest that disables an already-disabled ref is invisible (L5 round 8).')
    w('- Counts are statement occurrences, not distinct reachable paths: conditional statements are included (flag `conditional` in gaps.json).')
    return '\n'.join(L) + '\n'


def md_policy(notes, d, inv, patch):
    rules = policy.load_rules()['quests']
    L = [notes.rstrip(), '', '## Appendix: per-quest rule status (generated)', '',
         '| quest | assigned town | tier | rules.json today | patch: add | patch: merge params |', '|---|---|---|---|---|---|']
    n_have = 0
    for iv in inv:
        e = iv['edid']
        have = [r['kind'] for r in rules.get(e, {}).get('rules', [])]
        n_have += 1 if e in rules else 0
        pq = patch['quests'].get(e) or patch['new_quests'].get(e) or {}
        adds = [a['kind'] for a in pq.get('add', [])]
        sp = list((pq.get('set_params') or {}).keys())
        L.append('| %s | %s | %s | %s | %s | %s |' % (e, iv['town_assignment'], iv['tier'], ', '.join(have) if e in rules else '(no entry)', ', '.join(adds) or '-', ', '.join(sp) or '-'))
    L += ['', '%d of %d quests have a rules.json entry today; the patch extends %d existing entries and creates %d new ones.'
          % (n_have, len(inv), len(patch['quests']), len(patch['new_quests'])), '']
    return chr(10).join(L)


def md_dialogue(rows, notes, specs):
    L = []
    w = L.append
    w('# Towns questline: key conversations')
    w('')
    w('Generated rows (from `infos.jsonl.gz` + `dials.json.gz`) followed by hand-written analysis. Style follows `plugin/dialogue/` specs and '
      '`docs/dialogue-design.md`: initiator picks the line, everyone sees line + result, speech/skill checks run on the initiator, rewards are shared.')
    w('')
    n_skill = sum(1 for r in rows if r['skill_checks'])
    n_branch = sum(1 for r in rows if r['branches_quest'])
    n_rec = sum(1 for r in rows if r['recruit'])
    n_fac = sum(1 for r in rows if r['faction_or_stat'])
    n_rep = sum(1 for r in rows if r['rep_faction_conds'])
    n_inv = sum(1 for r in rows if r['player_conds'])
    w('Flagged INFOs: %d (skill/attribute checks %d, quest-branching results %d, companion/team results %d, faction/reputation/karma/combat-relation results %d, '
      'reputation/faction conditions %d, inventory/perk/sex conditions %d).' % (len(rows), n_skill, n_branch, n_rec, n_fac, n_rep, n_inv))
    w('')

    def table(title, sel, cols_fn, limit=40):
        sub = [r for r in rows if sel(r)]
        w('## %s (%d)' % (title, len(sub)))
        w('')
        if not sub:
            w('none.')
            w('')
            return
        w('| quest | INFO | topic prompt | speaker | detail | NPC line |')
        w('|---|---|---|---|---|---|')
        for r in sub[:limit]:
            w('| %s | %s | %s | %s | %s | %s |' % (r['quest'], r['info'].split(':')[1], (r['prompt'] or r['topic_edid'] or '').replace('|', '/')[:40],
                                                  r['speaker'] or '', cols_fn(r).replace('|', '/')[:150], r['line'].replace('|', '/')[:70]))
        if len(sub) > limit:
            w('')
            w('... %d more in dialogue_data.json' % (len(sub) - limit))
        w('')
    table('Speech / skill / attribute checks', lambda r: r['skill_checks'],
          lambda r: '; '.join('%s %s %g on %s' % (a, b, c, e) for a, b, c, e in r['skill_checks']))
    table('Conversation results that branch the questline', lambda r: r['branches_quest'] and not r['skill_checks'],
          lambda r: ', '.join(r['script_fns']) + ' :: ' + r['result_excerpt'][:90])
    table('Companion / team results', lambda r: r['recruit'], lambda r: r['result_excerpt'])
    table('Faction / reputation / karma / relation results', lambda r: r['faction_or_stat'] and not r['recruit'],
          lambda r: ', '.join(r['script_fns']))
    table('Reputation / faction-gated lines', lambda r: r['rep_faction_conds'] and not r['skill_checks'],
          lambda r: '; '.join('%s %s %s %g' % (a, b, c, e) for a, b, c, e in r['rep_faction_conds']))
    table('Inventory / perk / sex-gated lines', lambda r: r['player_conds'] and not r['skill_checks'],
          lambda r: '; '.join('%s %s %s %g' % (a, b, c, e) for a, b, c, e in r['player_conds']))
    w('## L8-style scenario specs generated for the key checks')
    w('')
    w('`dialogue_specs.json` holds %d specs (pass/fail pair per check) in the `plugin/dialogue/scenarios` schema; every FormID is looked up from the data '
      '(`questlines/towns/run_tests.py` re-resolves them). `greeting_info` is null: unknown, L8 fills it from the dialogue recorder.' % len(specs))
    w('')
    for s in specs:
        st = s['steps'][2]
        w('- `%s`: %s; INFO %s on topic %s; expects %s' % (s['id'], s['name'], st['info'].split(':')[1], (st['topic_edid'] or st['topic']),
                                                          json.dumps({k: v for k, v in st['expect'].items() if k not in ('spectator_lines', 'converged')}, sort_keys=True)))
    w('')
    w('Example (first spec):')
    w('')
    w('```json')
    w(json.dumps(specs[0], indent=1))
    w('```')
    w('')
    w(notes)
    return '\n'.join(L) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=HERE)
    a = ap.parse_args(argv)
    d = lib.Data()
    inv, sw, items, th, summ, patch, dlg = build_all(d)
    dump(os.path.join(a.out, 'inventory.json'), {'questline': 'towns', 'generated_from': 'out/questdata', 'count': len(inv), 'quests': inv})
    dump(os.path.join(a.out, 'sweep.json'), sw)
    dump(os.path.join(a.out, 'gaps.json'), {'questline': 'towns', 'summary': summ, 'text_hazards': th, 'items': items})
    with open(os.path.join(a.out, 'gaps.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(md_gaps(items, th, summ, inv))
    dump(os.path.join(a.out, 'rules.patch.json'), patch)
    pn = os.path.join(HERE, 'policy_review_notes.md')
    with open(os.path.join(a.out, 'policy_review.md'), 'w', encoding='utf-8', newline=chr(10)) as f:
        f.write(md_policy(open(pn, encoding='utf-8').read(), d, inv, patch))
    dump(os.path.join(a.out, 'dialogue_data.json'), {'questline': 'towns', 'rows': dlg})
    specs = analysis.dialogue_specs(d)
    dump(os.path.join(a.out, 'dialogue_specs.json'), {'questline': 'towns', 'specs': specs})
    notes_path = os.path.join(HERE, 'dialogue_notes.md')
    notes = open(notes_path, encoding='utf-8').read() if os.path.exists(notes_path) else ''
    with open(os.path.join(a.out, 'dialogue.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(md_dialogue(dlg, notes, specs))
    print('inventory %d quests, sweep %s, gaps %d items %s, patch quests %d new %d, dialogue rows %d'
          % (len(inv), sw['summary'], len(items), summ['by_severity'], len(patch['quests']), len(patch['new_quests']), len(dlg)))


if __name__ == '__main__':
    main()
